using Gori.Common.Roslyn.Test;
using Gori.CompressedStatics.CSharp;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Gori.CompressedStatics.Testing;

public sealed class ScopedRewriterTests
{
    public static TheoryData<bool, bool> RewriteOptions
        => [
            new(false, false) { Label = "Cleanup only" },
            new(true, false) { Label = "Types only" },
            new(false, true) { Label = "Extensions only" },
            new(true, true) { Label = "Types and extensions" },
        ];

    [Theory]
    [MemberData(nameof(RewriteOptions))]
    public async Task RewritesWithinNestedTypesAndPreservesOtherAttributes(bool rewriteTypes, bool rewriteExtensions)
    {
        const string source = """
            using System;
            using Example;
            namespace Example
            {
                public static class Extensions
                {
                    public static T Echo<T>(this T value) => value;
                }
                // Preserve this comment.
                [Obsolete]
                public partial class Outer
                {
                    public class Nested
                    {
                        public DateTime Run(DateTime value) => value.Echo().Echo();
                    }
                }
                public partial class Outer { }
                public class Sibling
                {
                    public DateTime Run(DateTime value) => value.Echo();
                }
            }
            """;
        var project = MockProject.Create(typeof(CSharpRewriterIgnoreAttribute).Assembly, source, cancellationToken: TestContext.Current.CancellationToken);
        Compilation compilation = await project.GetCompilationAsync();
        var rewriter = new CSharpRewriter
        {
            RewritePublicToInternal = false,
            AddAutoGeneratedAttribute = false,
            AddAutoGeneratedHeader = false,
            AddEmbeddedAttribute = false,
            AddNullableDirective = false,
            RewriteTypeNames = rewriteTypes,
            RewriteExtensionCalls = rewriteExtensions,
        };

        string result = rewriter.Rewrite(source, compilation, out IEnumerable<RewriteIssue> issues, TestContext.Current.CancellationToken);
        Assert.Empty(issues);
        SyntaxTree tree = CSharpSyntaxTree.ParseText(result, cancellationToken: TestContext.Current.CancellationToken);
        SyntaxNode root = await tree.GetRootAsync(TestContext.Current.CancellationToken);
        AttributeSyntax attribute = Assert.Single(root.DescendantNodes().OfType<AttributeSyntax>());
        Assert.Equal(rewriteTypes ? "global::System.ObsoleteAttribute" : "Obsolete", attribute.Name.ToString());
        Assert.Contains("// Preserve this comment.", result);
        Assert.All(root.DescendantNodes().OfType<MethodDeclarationSyntax>().Where(method => method.Identifier.ValueText == "Run"),
            method => Assert.Equal(rewriteTypes ? "global::System.DateTime" : "DateTime", method.ReturnType.ToString()));
        InvocationExpressionSyntax[] invocations = [.. root.DescendantNodes().OfType<InvocationExpressionSyntax>()];
        Assert.Equal(3, invocations.Length);
        Assert.All(invocations, invocation => Assert.Equal(rewriteExtensions,
            invocation.Expression.ToString().StartsWith("global::Example.Extensions.Echo<", StringComparison.Ordinal)));
        Assert.Equal(!(rewriteTypes && rewriteExtensions), root.DescendantNodes().OfType<UsingDirectiveSyntax>().Any(usingDirective => usingDirective.Name?.ToString() == "Example"));

        SyntaxTree original = Assert.Single(compilation.SyntaxTrees, candidate => candidate.GetText(TestContext.Current.CancellationToken).ToString() == source);
        Compilation rewritten = compilation.ReplaceSyntaxTree(original, tree);
        Assert.Empty(rewritten.GetDiagnostics(TestContext.Current.CancellationToken).Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error));
    }
}
