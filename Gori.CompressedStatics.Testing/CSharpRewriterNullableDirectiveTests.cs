using Gori.Common.Roslyn.Test;
using Gori.CompressedStatics.CSharp;

using Microsoft.CodeAnalysis;

namespace Gori.CompressedStatics.Testing;

public sealed class CSharpRewriterNullableDirectiveTests
{
    public static TheoryData<string> NullablePropertySources
        => [
            new("class Sample { public string? Name { get; set; } }") { Label = "Nullable reference property" },
            new("class Sample { public global::System.Collections.Generic.List<string?> Names { get; set; } }") { Label = "Nested nullable generic argument" },
            new("class Sample { public string? this[int index] => null; }") { Label = "Nullable indexer" },
        ];

    [Theory]
    [MemberData(nameof(NullablePropertySources))]
    public async Task AddsDirectiveWhenPropertyTypeContainsNullableAnnotation(string source)
    {
        string result = await Rewrite(source, new CSharpRewriter
        {
            AddNullableDirective = true,
            AddAutoGeneratedHeader = false,
        });

        Assert.StartsWith("#nullable enable\n", result, StringComparison.Ordinal);
    }

    [Fact]
    public async Task DoesNotAddDirectiveWhenThereAreNoNullablePropertyTypes()
    {
        const string source = "class Sample { public string Name { get; set; } public string? GetName() => null; }";

        string result = await Rewrite(source, new CSharpRewriter { AddNullableDirective = true });

        Assert.DoesNotContain("#nullable", result, StringComparison.Ordinal);
    }

    [Fact]
    public async Task ExistingNullableDirectiveAnywherePreventsInsertion()
    {
        const string source = "class Sample { public string? Name { get; set; } }\n#nullable disable\n";

        string result = await Rewrite(source, new CSharpRewriter { AddNullableDirective = true });

        Assert.DoesNotContain("#nullable enable", result, StringComparison.Ordinal);
        Assert.Contains("#nullable disable", result, StringComparison.Ordinal);
    }

    [Fact]
    public async Task NullableDirectiveInDisabledRegionPreventsInsertion()
    {
        const string source = "#if false\n#nullable disable\n#endif\nclass Sample { public string? Name { get; set; } }";

        string result = await Rewrite(source, new CSharpRewriter { AddNullableDirective = true });

        Assert.DoesNotContain("#nullable enable", result, StringComparison.Ordinal);
        Assert.Contains("#nullable disable", result, StringComparison.Ordinal);
    }

    [Fact]
    public async Task DisabledOptionDoesNotAddDirective()
    {
        const string source = "class Sample { public string? Name { get; set; } }";

        string result = await Rewrite(source, new CSharpRewriter { AddNullableDirective = false });

        Assert.DoesNotContain("#nullable", result, StringComparison.Ordinal);
    }

    [Fact]
    public async Task DirectiveFollowsGeneratedHeaderAndUsesSourceLineEnding()
    {
        const string source = "class Sample { public string? Name { get; set; } }\r\n";
        var rewriter = new CSharpRewriter { AddAutoGeneratedHeader = true, AddNullableDirective = true };

        string result = await Rewrite(source, rewriter);

        Assert.StartsWith("// <auto-generated />\r\n#nullable enable\r\n", result, StringComparison.Ordinal);
    }

    [Fact]
    public async Task ExistingGeneratedHeaderRemainsBeforeInsertedDirective()
    {
        const string source = "// <auto-generated />\nclass Sample { public string? Name { get; set; } }";
        var rewriter = new CSharpRewriter { AddAutoGeneratedHeader = true, AddNullableDirective = true };

        string result = await Rewrite(source, rewriter);

        Assert.StartsWith("// <auto-generated />\n#nullable enable\n", result, StringComparison.Ordinal);
    }

    [Fact]
    public void EqualityIncludesNullableDirectiveOption()
    {
        var withoutDirective = new CSharpRewriter { AddNullableDirective = false };
        var withDirective = new CSharpRewriter { AddNullableDirective = true };

        Assert.NotEqual(withoutDirective, withDirective);
    }

    private static async Task<string> Rewrite(string source, CSharpRewriter rewriter)
    {
        var project = MockProject.Create(typeof(CSharpRewriter).Assembly, source, cancellationToken: TestContext.Current.CancellationToken);
        Compilation compilation = await project.GetCompilationAsync();

        return rewriter.Rewrite(source, compilation, out _, TestContext.Current.CancellationToken);
    }
}
