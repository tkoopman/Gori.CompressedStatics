using Gori.Common.Roslyn.Test;
using Gori.CompressedStatics.CSharp;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Gori.CompressedStatics.Testing;

public sealed class TopLevelRewriterAttributeTests(ITestOutputHelper output)
{
    public static TheoryData<bool, bool> AttributeOptions
        => [
            new(false, false) { Label = "Neither attribute" },
            new(true, false) { Label = "GeneratedCode only" },
            new(false, true) { Label = "Embedded only" },
            new(true, true) { Label = "Both attributes" },
        ];

    [Theory]
    [MemberData(nameof(AttributeOptions))]
    public async Task AddsAttributesOnlyToTopLevelTypes(bool generatedCode, bool embedded)
    {
        const string source = """
            using System;
            namespace Microsoft.CodeAnalysis
            {
                internal sealed class EmbeddedAttribute : Attribute { }
            }
            namespace Targets
            {
                public class Container
                {
                    public class Nested { public DateTime Value; }
                    public struct NestedStruct { }
                    public record NestedRecord;
                    public record struct NestedRecordStruct;
                    public interface NestedInterface { }
                    public enum NestedEnum { Value }
                    public delegate void NestedDelegate();
                    [global::System.CodeDom.Compiler.GeneratedCode("Existing", "1")]
                    [global::Microsoft.CodeAnalysis.Embedded]
                    public class AlreadyAttributed { public class Deeper { } }
                }
                public struct TopStruct { }
                public record TopRecord;
                public record struct TopRecordStruct;
                public interface TopInterface { }
                public enum TopEnum { Value }
                public delegate void TopDelegate();
            }
            """;
        var project = MockProject.Create(typeof(CSharpRewriterIgnoreAttribute).Assembly, source, cancellationToken: TestContext.Current.CancellationToken);
        Compilation compilation = await project.GetCompilationAsync();
        var rewriter = new CSharpRewriter
        {
            AddAutoGeneratedAttribute = generatedCode,
            AddEmbeddedAttribute = embedded,
            RewriteTypeNames = true,
        };

        string result = rewriter.Rewrite(source, compilation, out IEnumerable<RewriteIssue> issues, TestContext.Current.CancellationToken);
        output.WriteLine($"GeneratedCode: {generatedCode}; Embedded: {embedded}");
        output.WriteLine($"Input:\n{source}\n\nRewritten output:\n{result}");
        Assert.Empty(issues);
        SyntaxNode root = await CSharpSyntaxTree.ParseText(result, cancellationToken: TestContext.Current.CancellationToken)
            .GetRootAsync(TestContext.Current.CancellationToken);

        NamespaceDeclarationSyntax targets = Assert.Single(root.DescendantNodes().OfType<NamespaceDeclarationSyntax>(),
            declaration => declaration.Name.ToString() == "Targets");

        Assert.Equal(7, targets.Members.Count);
        Assert.All(targets.Members, declaration =>
        {
            AttributeSyntax[] attributes = GetAttributes(declaration);
            Assert.Equal((generatedCode ? 1 : 0) + (embedded ? 1 : 0), attributes.Length);
            Assert.Equal(generatedCode, attributes.Any(attribute => attribute.Name.ToString() == "global::System.CodeDom.Compiler.GeneratedCode"));
            Assert.Equal(embedded, attributes.Any(attribute => attribute.Name.ToString() == "global::Microsoft.CodeAnalysis.Embedded"));
            Assert.All(attributes, attribute =>
            {
                AttributeListSyntax list = Assert.IsType<AttributeListSyntax>(attribute.Parent);
                _ = Assert.Single(list.Attributes);
                Assert.Contains(list.GetTrailingTrivia(), trivia => trivia.IsKind(SyntaxKind.EndOfLineTrivia));
            });
        });

        ClassDeclarationSyntax container = Assert.Single(targets.Members.OfType<ClassDeclarationSyntax>());
        MemberDeclarationSyntax[] nested = [.. container.DescendantNodes().OfType<MemberDeclarationSyntax>()
            .Where(declaration => declaration is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax)];

        Assert.Equal(9, nested.Length);
        Assert.All(nested.Where(declaration => declaration is not ClassDeclarationSyntax { Identifier.ValueText: "AlreadyAttributed" }),
            declaration => Assert.Empty(GetAttributes(declaration)));

        ClassDeclarationSyntax existing = Assert.Single(nested.OfType<ClassDeclarationSyntax>(),
            declaration => declaration.Identifier.ValueText == "AlreadyAttributed");

        AttributeSyntax[] existingAttributes = GetAttributes(existing);
        Assert.Equal(2, existingAttributes.Length);
        Assert.Equal(["Existing", "1"], existingAttributes[0].ArgumentList!.Arguments
            .Select(argument => argument.Expression.GetFirstToken().ValueText));

        Assert.Equal("global::Microsoft.CodeAnalysis.Embedded", existingAttributes[1].Name.ToString());
        Assert.Contains("global::System.DateTime Value", result);
    }

    public static TheoryData<string> CommentedTypes
        => [
            new("public class Sample { }") { Label = "Class" },
            new("public struct Sample { }") { Label = "Struct" },
            new("public record Sample;") { Label = "Record" },
            new("public record struct Sample;") { Label = "Record struct" },
            new("public interface Sample { }") { Label = "Interface" },
            new("public enum Sample { Value }") { Label = "Enum" },
            new("public delegate void Sample();") { Label = "Delegate" },
        ];

    [Theory]
    [MemberData(nameof(CommentedTypes))]
    public async Task AddedAttributesFollowExistingAttributesOrTypeCommentsAndPreserveIndentation(string declaration)
    {
        foreach (string existingAttribute in new[] { string.Empty, "    [System.Obsolete]\n" })
        {
            string source = "namespace Targets\n{\n" + existingAttribute
                + "    // Type comment.\n    /// <summary>Type documentation.</summary>\n    " + declaration + "\n}";

            var project = MockProject.Create(typeof(CSharpRewriterIgnoreAttribute).Assembly, source,
                cancellationToken: TestContext.Current.CancellationToken);

            var rewriter = new CSharpRewriter();
            string result = rewriter.Rewrite(source, await project.GetCompilationAsync(), out IEnumerable<RewriteIssue> issues,
                TestContext.Current.CancellationToken);

            output.WriteLine(existingAttribute.Length == 0 ? "No existing type attributes" : "Existing type attribute before comments");
            output.WriteLine($"Input:\n{source}\n\nRewritten output:\n{result}\n");
            Assert.Empty(issues);
            if (existingAttribute.Length == 0)
            {
                Assert.Contains("    // Type comment.\n    /// <summary>Type documentation.</summary>\n    [global::System.CodeDom.Compiler.GeneratedCode", result);
                Assert.Contains("]\n    [global::Microsoft.CodeAnalysis.Embedded]\n    internal ", result);
            }
            else
            {
                Assert.Contains("    [global::System.ObsoleteAttribute]\n    [global::System.CodeDom.Compiler.GeneratedCode", result);
                Assert.Contains("]\n    [global::Microsoft.CodeAnalysis.Embedded]\n    // Type comment.\n    /// <summary>Type documentation.</summary>\n    internal ", result);
            }

            Assert.Equal(1, result.Split("// Type comment.", StringSplitOptions.None).Length - 1);
            Assert.Equal(1, result.Split("/// <summary>Type documentation.</summary>", StringSplitOptions.None).Length - 1);
        }
    }

    [Theory]
    [MemberData(nameof(CommentedTypes))]
    public async Task AssemblyAttributeRemainsSeparateFromAddedTypeAttributes(string declaration)
    {
        string source = "[assembly: System.Reflection.AssemblyMetadata(\"Key\", \"Value\")]\n\n"
            + "// Type comment.\n/// <summary>Type documentation.</summary>\n" + declaration;

        var project = MockProject.Create(typeof(CSharpRewriterIgnoreAttribute).Assembly, source,
            cancellationToken: TestContext.Current.CancellationToken);

        string result = new CSharpRewriter().Rewrite(source, await project.GetCompilationAsync(),
            out IEnumerable<RewriteIssue> issues, TestContext.Current.CancellationToken);

        output.WriteLine("Assembly attribute followed by a commented type");
        output.WriteLine($"Input:\n{source}\n\nRewritten output:\n{result}");
        CompilationUnitSyntax root = CSharpSyntaxTree.ParseText(result, cancellationToken: TestContext.Current.CancellationToken)
            .GetCompilationUnitRoot(TestContext.Current.CancellationToken);

        Assert.Empty(issues);
        AttributeListSyntax assemblyList = Assert.Single(root.AttributeLists);
        Assert.Equal("assembly", assemblyList.Target!.Identifier.ValueText);
        AttributeSyntax assemblyAttribute = Assert.Single(assemblyList.Attributes);
        Assert.Equal("global::System.Reflection.AssemblyMetadataAttribute", assemblyAttribute.Name.ToString());
        Assert.Equal(["Key", "Value"], assemblyAttribute.ArgumentList!.Arguments
            .Select(argument => argument.Expression.GetFirstToken().ValueText));

        AttributeSyntax[] typeAttributes = GetAttributes(Assert.Single(root.Members));
        Assert.Equal(2, typeAttributes.Length);
        Assert.Equal("global::System.CodeDom.Compiler.GeneratedCode", typeAttributes[0].Name.ToString());
        Assert.Equal("global::Microsoft.CodeAnalysis.Embedded", typeAttributes[1].Name.ToString());
        Assert.All(typeAttributes, attribute =>
        {
            AttributeListSyntax list = Assert.IsType<AttributeListSyntax>(attribute.Parent);
            Assert.Null(list.Target);
            _ = Assert.Single(list.Attributes);
        });

        Assert.Contains("// Type comment.\n/// <summary>Type documentation.</summary>\n[global::System.CodeDom.Compiler.GeneratedCode", result);
        Assert.Contains("]\n[global::Microsoft.CodeAnalysis.Embedded]\ninternal ", result);
        Assert.True(assemblyList.Span.End < typeAttributes[0].Span.Start);
    }

    private static AttributeSyntax[] GetAttributes(MemberDeclarationSyntax declaration)
        => declaration switch
        {
            BaseTypeDeclarationSyntax type => [.. type.AttributeLists.SelectMany(list => list.Attributes)],
            DelegateDeclarationSyntax type => [.. type.AttributeLists.SelectMany(list => list.Attributes)],
            _ => throw new ArgumentException("Expected a type declaration.", nameof(declaration)),
        };
}
