    [Theory]
    [MemberData(nameof(ExtensionCallCases))]
    public async Task CSharpTransformerRewritesExtensionCallsWithoutChangingBehavior(string source, string expectedFragment, int expectedValue, bool retainsImport)
    {
        CommonMockProject project = CreateProject(source);
        Compilation compilation = await project.GetCompilationAsync();
        Assert.Empty(compilation.GetDiagnostics(TestContext.Current.CancellationToken)
            .Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error));
        var transformer = new CSharpRewriterTransformer(CSharpRewriterOptions.RewriteTypeNames | CSharpRewriterOptions.RewriteExtensionCalls);

        Assert.True(transformer.TryTransform(
            CreateTransformerInput(source),
            compilation,
            out string? transformed,
            out DiagnosticInfo? diagnostic,
            TestContext.Current.CancellationToken));

        Assert.Null(diagnostic);
        Assert.NotNull(transformed);
        output.WriteLine(transformed);
        Assert.Contains(expectedFragment, transformed, StringComparison.Ordinal);
        Assert.Equal(retainsImport, transformed.Contains("using ", StringComparison.Ordinal));
        SyntaxTree sourceTree = compilation.SyntaxTrees.Single(tree => tree.GetText().ToString() == source);

        Compilation rewritten = compilation.ReplaceSyntaxTree(
            sourceTree,
            CSharpSyntaxTree.ParseText(
                transformed,
                (CSharpParseOptions)sourceTree.Options,
                cancellationToken: TestContext.Current.CancellationToken));

        using var stream = new MemoryStream();
        EmitResult result = rewritten.Emit(stream, cancellationToken: TestContext.Current.CancellationToken);
        Assert.True(result.Success, string.Join(Environment.NewLine, result.Diagnostics));
        stream.Position = 0;
        var context = new AssemblyLoadContext(nameof(CSharpTransformerRewritesExtensionCallsWithoutChangingBehavior), isCollectible: true);
        try
        {
            Type sample = context.LoadFromStream(stream).GetType("Sample")!;
            Assert.Equal(expectedValue, Assert.IsType<int>(sample.GetMethod("Read")!.Invoke(null, null)));
        }
        finally
        {
            context.Unload();
        }
    }

