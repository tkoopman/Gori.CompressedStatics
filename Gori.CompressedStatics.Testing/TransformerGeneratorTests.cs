    [Theory]
    [MemberData(nameof(GeneratedCodeAssemblyCases))]
    public async Task CSharpTransformerGeneratedCodeAttributeUsesConsumerAssembly(string assemblyName, string? assemblyVersion)
    {
        const string source = "namespace Templates { public class Outer { public class Inner { } public delegate void Callback(); } [global::System.CodeDom.Compiler.GeneratedCode(\"Existing.Tool\", \"1.2\")] public class Existing { } }";
        CommonMockProject project = CreateProject(source);
        _ = project.AddDocument(
            (assemblyVersion is null ? string.Empty : $"[assembly: System.Reflection.AssemblyVersion(\"{assemblyVersion}\")]\n")
            + "[assembly: System.Reflection.AssemblyInformationalVersion(\"99.0.0-preview\")]",
            "src\\AssemblyInfo.cs");
        Compilation compilation = (await project.GetCompilationAsync()).WithAssemblyName(assemblyName);
        var transformer = new CSharpRewriterTransformer(CSharpRewriterOptions.AddAutoGeneratedAttribute);

        bool success = transformer.TryTransform(
            CreateTransformerInput(source), compilation, out string? transformed, out DiagnosticInfo? diagnostic,
            TestContext.Current.CancellationToken);

        Assert.True(success);
        Assert.Null(diagnostic);
        Assert.NotNull(transformed);
        AttributeSyntax[] attributes = [.. CSharpSyntaxTree.ParseText(transformed, cancellationToken: TestContext.Current.CancellationToken)
            .GetRoot(TestContext.Current.CancellationToken)
            .DescendantNodes().OfType<AttributeSyntax>()];
        Assert.Equal(4, attributes.Length);

        foreach (AttributeSyntax? attribute in attributes.Take(3))
        {
            Assert.Equal("global::System.CodeDom.Compiler.GeneratedCode", attribute.Name.ToString());
            Assert.NotNull(attribute.ArgumentList);
            Assert.Equal(
                new[] { assemblyName, assemblyVersion ?? "0.0.0.0" },
                attribute.ArgumentList.Arguments.Select(argument => argument.Expression.GetFirstToken().ValueText));
        }

        Assert.Contains("GeneratedCode(\"Existing.Tool\", \"1.2\")", transformed, StringComparison.Ordinal);
        bool repeatedSuccess = transformer.TryTransform(
            CreateTransformerInput(transformed), compilation, out string? repeatedOutput, out diagnostic,
            TestContext.Current.CancellationToken);
        Assert.True(repeatedSuccess);
        Assert.Null(diagnostic);
        Assert.Equal(transformed, repeatedOutput);
    }

