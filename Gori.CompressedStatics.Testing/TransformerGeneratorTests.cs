    public sealed class PrefixStringTransformer : IStringTransformer
    {
        public bool TryTransform(
            ICompressionAttributeInfo attribute,
            Compilation compilation,
            [NotNullWhen(true)] out string? output,
            [NotNullWhen(false)] out DiagnosticInfo? diagnostic,
            CancellationToken cancellationToken)
        {
            cancellationToken.ThrowIfCancellationRequested();
            output = "processed:" + attribute.SourceValue;
            diagnostic = null;
            return true;
        }
    }

    public sealed class HexBinaryTransformer : IBinaryTransformer
    {
        public bool TryTransform(
            ICompressionAttributeInfo attribute,
            Compilation compilation,
            [NotNullWhen(true)] out byte[]? output,
            [NotNullWhen(false)] out DiagnosticInfo? diagnostic,
            CancellationToken cancellationToken)
        {
            cancellationToken.ThrowIfCancellationRequested();
            try
            {
                output = Convert.FromHexString(attribute.SourceValue ?? string.Empty);
                diagnostic = null;
                return true;
            }
            catch (FormatException exception)
            {
                output = null;
                diagnostic = new DiagnosticInfo(
                    DiagnosticDescriptors.TransformerExceptionThrown,
                    attribute.MemberName,
                    nameof(HexBinaryTransformer),
                    exception.Message);
                return false;
            }
        }
    }
