using System.Collections.Immutable;

using Gori.Common.Roslyn.Test;
using Gori.CompressedStatics.Generators;

using Microsoft.CodeAnalysis;

namespace Gori.CompressedStatics.Testing;

public sealed class CSharpRewriterOptionsTests
{
    public static TheoryData<CSharpRewriterOptions> Options
        => [
            new(CSharpRewriterOptions.None) { Label = "None" },
            new(CSharpRewriterOptions.Basic) { Label = "Basic" },
            new(CSharpRewriterOptions.Default) { Label = "Default" },
            new(CSharpRewriterOptions.RewritePublicToInternal) { Label = "Public to internal only" },
            new(CSharpRewriterOptions.AddAutoGeneratedAttribute) { Label = "Generated attribute only" },
            new(CSharpRewriterOptions.AddAutoGeneratedHeader) { Label = "Header only" },
            new(CSharpRewriterOptions.AddEmbeddedAttribute) { Label = "Embedded attribute only" },
            new(CSharpRewriterOptions.AddGlobalUsings) { Label = "Global usings only" },
            new(CSharpRewriterOptions.AddNullableDirective) { Label = "Nullable directive only" },
            new(CSharpRewriterOptions.RewriteTypeNames) { Label = "Global names only" },
            new(CSharpRewriterOptions.AggressiveImportRemoval) { Label = "Import removal only" },
            new(CSharpRewriterOptions.RewriteExtensionCalls) { Label = "Extension calls only" },
            new(CSharpRewriterOptions.All) { Label = "All flags" },
            new(CSharpRewriterOptions.Default & ~CSharpRewriterOptions.AddEmbeddedAttribute) { Label = "Exclude embedded attribute" },
        ];

    [Theory]
    [MemberData(nameof(Options))]
    public void ConstructorEnablesExactlyTheSelectedFlags(CSharpRewriterOptions options)
    {
        var transformer = new CSharpRewriterTransformer(options);
        Assert.Equal(options.HasFlag(CSharpRewriterOptions.RewritePublicToInternal), transformer.RewritePublicToInternal);
        Assert.Equal(options.HasFlag(CSharpRewriterOptions.AddAutoGeneratedAttribute), transformer.AddAutoGeneratedAttribute);
        Assert.Equal(options.HasFlag(CSharpRewriterOptions.AddAutoGeneratedHeader), transformer.AddAutoGeneratedHeader);
        Assert.Equal(options.HasFlag(CSharpRewriterOptions.AddEmbeddedAttribute), transformer.AddEmbeddedAttribute);
        Assert.Equal(options.HasFlag(CSharpRewriterOptions.AddGlobalUsings), transformer.AddGlobalUsings);
        Assert.Equal(options.HasFlag(CSharpRewriterOptions.AddNullableDirective), transformer.AddNullableDirective);
        Assert.Equal(options.HasFlag(CSharpRewriterOptions.RewriteTypeNames), transformer.RewriteTypeNames);
        Assert.Equal(options.HasFlag(CSharpRewriterOptions.AggressiveImportRemoval), transformer.AggressiveImportRemoval);
        Assert.Equal(options.HasFlag(CSharpRewriterOptions.RewriteExtensionCalls), transformer.RewriteExtensionCalls);
    }

    [Fact]
    public void ParameterlessConstructorUsesDefaultsAndAllowsInitOverrides()
    {
        var transformer = new CSharpRewriterTransformer();
        Assert.True(transformer.RewritePublicToInternal);
        Assert.True(transformer.AddAutoGeneratedAttribute);
        Assert.True(transformer.AddAutoGeneratedHeader);
        Assert.True(transformer.AddEmbeddedAttribute);
        Assert.True(transformer.AddGlobalUsings);
        Assert.True(transformer.AddNullableDirective);
        Assert.True(transformer.RewriteTypeNames);
        Assert.False(transformer.AggressiveImportRemoval);
        Assert.True(transformer.RewriteExtensionCalls);
        Assert.True(new CSharpRewriterTransformer(CSharpRewriterOptions.None) { AddAutoGeneratedHeader = true }.AddAutoGeneratedHeader);
        Assert.False(new CSharpRewriterTransformer { RewriteExtensionCalls = false }.RewriteExtensionCalls);
    }

    [Fact]
    public void GroupsContainExactlyTheIntendedOptions()
    {
        Assert.Equal(CSharpRewriterOptions.RewritePublicToInternal | CSharpRewriterOptions.AddAutoGeneratedHeader | CSharpRewriterOptions.AddEmbeddedAttribute
            | CSharpRewriterOptions.AddNullableDirective | CSharpRewriterOptions.AddGlobalUsings,
            CSharpRewriterOptions.Basic);
        Assert.Equal(CSharpRewriterOptions.Basic | CSharpRewriterOptions.AddAutoGeneratedAttribute | CSharpRewriterOptions.RewriteTypeNames
            | CSharpRewriterOptions.RewriteExtensionCalls, CSharpRewriterOptions.Default);
        Assert.Equal(CSharpRewriterOptions.Default | CSharpRewriterOptions.AggressiveImportRemoval, CSharpRewriterOptions.All);
        Assert.Equal(511, (int)CSharpRewriterOptions.All);
    }

    [Fact]
    public void UnknownFlagsAreRejected()
        => Assert.Throws<ArgumentOutOfRangeException>(() => new CSharpRewriterTransformer((CSharpRewriterOptions)512));

    [Theory]
    [MemberData(nameof(Options))]
    public async Task GeneratedMarkerEnumConfiguresTheHostTransformer(CSharpRewriterOptions options)
    {
        var project = new MockProject(typeof(CompressFileAttribute).Assembly, cancellationToken: TestContext.Current.CancellationToken);
        _ = project.AddDocument($$"""
            using Gori.CompressedStatics;
            public static partial class Sample
            {
                [CompressFile("payload.txt", Transformer = "CSharpRewriter",
                    TransformerArguments = [(CSharpRewriterOptions){{(int)options}}])]
                public static partial string Value { get; }
            }
            """, "src\\Sample.cs");
        const string payload = "public class Payload { public string? Value { get; set; } }";
        _ = project.AddAdditionalFile("src\\payload.txt", payload);
        Compilation compilation = await project.GetCompilationAsync();
        GeneratorDriver driver = project.CreateGeneratorDriver<CompressStaticsGenerator>()
            .AddGenerators([new AttributesGenerator().AsSourceGenerator()])
            .RunGeneratorsAndUpdateCompilation(compilation, out Compilation generated, out ImmutableArray<Diagnostic> diagnostics, TestContext.Current.CancellationToken);

        Assert.Empty(diagnostics);
        Assert.All(driver.GetRunResult().Results, result => Assert.Null(result.Exception));
        INamedTypeSymbol markerEnum = generated.GetTypeByMetadataName("Gori.CompressedStatics.CSharpRewriterOptions")!;
        Assert.NotNull(markerEnum);
        Assert.True(SymbolEqualityComparer.Default.Equals(markerEnum.ContainingAssembly, generated.Assembly));
        object value = Assert.Single(Assert.Single(driver.GetRunResult().Results.Where(result => result.TrackedSteps.ContainsKey(CompressStaticsGenerator.IndividualMemberTrackingName)))
            .TrackedSteps[CompressStaticsGenerator.IndividualMemberTrackingName].SelectMany(step => step.Outputs)).Value;
        CompressAttributeInfo member = Assert.IsType<(CompressAttributeInfo Input, Supports Supports)>(value).Input;
        var transformer = new CSharpRewriterTransformer(options);
        Assert.True(transformer.TryTransform(member.WithSourceValue(payload), compilation, out string? expected, out _, TestContext.Current.CancellationToken));
        Assert.Equal(options.HasFlag(CSharpRewriterOptions.AddNullableDirective), expected!.Contains("#nullable enable", StringComparison.Ordinal));
        Assert.Equal(expected, member.SourceValue);
    }
}
