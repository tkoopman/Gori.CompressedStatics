using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Gori.CompressedStatics.Generators;

/// <summary>
/// Provides functionality to emit source code for compressed members based on the specified compression algorithm and caching strategy.
/// </summary>
internal static class MemberEmitter
{
    /// <summary>
    /// Builds the generated source for a single individually compressed member, in its own file so
    /// the member re-compresses and re-emits only when its own input changes.
    /// </summary>
    /// <param name="context">The source production context.</param>
    /// <param name="member">The compression member input.</param>
    /// <param name="supports">The supported compression algorithms and their availability.</param>
    /// <returns>The generated source code as a string.</returns>
    public static string Emit(SourceProductionContext context, CompressAttributeInfo member, Supports supports)
    {
        context.CancellationToken.ThrowIfCancellationRequested();
        byte[] uncompressedData = member.IsValid ? member.GetUncompressedData() : [];

        CompressionAlgorithm algorithm = member.RequestedAlgorithm;
        byte[] compressedData = member.IsValid
            ? Compressor.Compress(uncompressedData, ref algorithm, supports.DisableBrotli, context.CancellationToken)
            : [];
        StorageKind storageKind = member.IsValid ? algorithm.ToStorageKind() : StorageKind.Raw;

        var builder = CodeStringBuilder.CodeStringBuilder.CreateCSharpBuilder();
        _ = builder.WriteLine($"// <auto-generated />")
                   .WriteLineIf(member.IsValid, () => $"// Compression algorithm: {storageKind}")
                   .WriteLineIf(member.IsValid, () => $"// Uncompressed: {uncompressedData.Length} bytes")
                   .WriteLineIf(
                        storageKind is not StorageKind.Raw,
                        () => $"// Compressed: {compressedData.Length} bytes - {(uncompressedData.Length == 0 ? 0.0 : (double)compressedData.Length / uncompressedData.Length):P2}")
                   .ForceBlankLine();

        string returnType = member.ReturnType.AsKeyword();
        string escapedMemberName = Helper.EscapeIdentifier(member.MemberName);

        Helper.AppendOpen(builder, member.ContainingType);
        switch (storageKind)
        {
            case StorageKind.Raw:
                string uncompressed = member.ReturnType is ReturnType.String
                        ? SymbolDisplay.FormatLiteral(Encoding.Unicode.GetString(uncompressedData), true)
                        : uncompressedData.BuildByteArrayLiteral();

                // If the member is a property returning a byte array, we can cache the uncompressed data directly.
                if (member.IsValid && member.MemberKind is MemberKind.Property && member.ReturnType is ReturnType.ByteArray)
                {
                    AppendCachedProperty(builder, member, uncompressed);
                    break;
                }

                string memberName = member.MemberKind switch
                {
                    MemberKind.Property => escapedMemberName,
                    MemberKind.Method => escapedMemberName + "()",
                    _ => throw new ArgumentOutOfRangeException(nameof(member), member.MemberKind, null),
                };

                _ = builder.WriteLine($"""
                        {member.Accessibility} static partial {returnType} {memberName}
                            => {uncompressed};{CodeStringBuilder.CodeStringBuilder.IndentDecreasePost}
                        """).ForceBlankLine();
                break;

            case StorageKind.Brotli:
            case StorageKind.GZip:
            case StorageKind.Deflate:
            default:
                string uniqueToken = Helper.Sanitize(member.MemberName);
                string compressedFieldName = Const.CompressedFieldNamePrefix + uniqueToken;
                string decompressCall = Helper.BuildDecompressCall(member.ReturnType, storageKind, compressedFieldName);

                _ = builder.WriteLine($"private static readonly byte[] {compressedFieldName} = {compressedData.BuildByteArrayLiteral()};")
                           .ForceBlankLine();

                switch (member.MemberKind)
                {
                    case MemberKind.Property:
                        AppendCachedProperty(builder, member, decompressCall);
                        break;

                    case MemberKind.Method:
                        _ = builder.WriteLine($"""
                                {member.Accessibility} static partial {returnType} {escapedMemberName}()
                                    => {decompressCall};{CodeStringBuilder.CodeStringBuilder.IndentDecreasePost}
                                """).ForceBlankLine();
                        break;

                    default:
                        throw new ArgumentOutOfRangeException(nameof(member), member.MemberKind, null);
                }

                break;
        }

        Helper.AppendClose(builder, member.ContainingType);

        return builder.ToString();
    }

    private static void AppendCachedProperty(CodeStringBuilder.CodeStringBuilder builder, CompressAttributeInfo member, string valueExpression)
    {
        string returnType = member.ReturnType.AsKeyword();
        string escapedMemberName = Helper.EscapeIdentifier(member.MemberName);
        string cacheFieldName = Const.CacheFieldNamePrefix + Helper.Sanitize(member.MemberName);

        _ = member.CacheMode switch
        {
            CompressionCacheMode.LazyThreadSafe
                => builder.WriteLine($"""
                            private static readonly global::System.Lazy<{returnType}> {cacheFieldName} = new(() => {valueExpression});

                            {member.Accessibility} static partial {returnType} {escapedMemberName} => {cacheFieldName}.Value;
                            """).ForceBlankLine(),

            CompressionCacheMode.Lazy
                => builder.WriteLine($"""
                            private static {returnType} {cacheFieldName};

                            {member.Accessibility} static partial {returnType} {escapedMemberName}
                                => {cacheFieldName} ??= {valueExpression};{CodeStringBuilder.CodeStringBuilder.IndentDecreasePost}
                            """).ForceBlankLine(),

            CompressionCacheMode.OnInit or _
                => builder.WriteLine($"""
                            private static readonly {returnType} {cacheFieldName} = {valueExpression};

                            {member.Accessibility} static partial {returnType} {escapedMemberName} => {cacheFieldName};
                            """).ForceBlankLine(),
        };
    }
}
