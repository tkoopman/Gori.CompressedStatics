using System.Diagnostics.CodeAnalysis;
using System.Globalization;

using Gori.CompressedStatics.Generators;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Gori.CompressedStatics;

/// <summary>
/// Input transformer that can edit c# code ready for use in source generators.
/// </summary>
public class CSharpRewriterTransformer : IStringTransformer
{
    /// <summary>
    /// Default instance.
    /// </summary>
    public static readonly CSharpRewriterTransformer Instance = new CSharpRewriterTransformer(CSharpRewriterOptions.Default);

    private const string ResolvedAttributeTypeAnnotation = "CSharpRewriter.ResolvedAttributeType";

    private static readonly SymbolDisplayFormat FullyQualifiedTypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    private static readonly SymbolDisplayFormat FullyQualifiedTypeFormatWithoutSpecialTypes = FullyQualifiedTypeFormat
        .WithMiscellaneousOptions(FullyQualifiedTypeFormat.MiscellaneousOptions & ~SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

    /// <summary>
    /// Initializes a new instance of the <see cref="CSharpRewriterTransformer"/> class
    /// with <see cref="CSharpRewriterOptions.Default"/> options.
    /// </summary>
    public CSharpRewriterTransformer()
        : this(CSharpRewriterOptions.Default)
    {
    }

    /// <summary>
    /// Initializes a new instance of the <see cref="CSharpRewriterTransformer"/> class with the selected options.
    /// </summary>
    /// <param name="options">The exact set of transformations to enable.</param>
    public CSharpRewriterTransformer(CSharpRewriterOptions options)
    {
        if ((options & ~CSharpRewriterOptions.All) != 0)
        {
            throw new ArgumentOutOfRangeException(nameof(options), options, "Unknown C# rewriter option flags.");
        }

        RewritePublicToInternal = (options & CSharpRewriterOptions.RewritePublicToInternal) != 0;
        AddAutoGeneratedAttribute = (options & CSharpRewriterOptions.AddAutoGeneratedAttribute) != 0;
        AddAutoGeneratedHeader = (options & CSharpRewriterOptions.AddAutoGeneratedHeader) != 0;
        AddEmbeddedAttribute = (options & CSharpRewriterOptions.AddEmbeddedAttribute) != 0;
        RewriteTypeNames = (options & CSharpRewriterOptions.RewriteTypeNames) != 0;
        AggressiveImportRemoval = (options & CSharpRewriterOptions.AggressiveImportRemoval) != 0;
        RewriteExtensionCalls = (options & CSharpRewriterOptions.RewriteExtensionCalls) != 0;
    }

    /// <summary>
    /// Gets a value indicating whether to change any public type to internal.
    /// NOTE: Only changes top-level types, nested types are not affected.
    /// </summary>
    public bool RewritePublicToInternal { get; init; }

    /// <summary>
    /// Gets a value indicating whether to add the <see cref="System.CodeDom.Compiler.GeneratedCodeAttribute"/> attribute
    /// using the consuming compilation's assembly name and assembly version.
    /// </summary>
    public bool AddAutoGeneratedAttribute { get; init; }

    /// <summary>
    /// Gets a value indicating whether to add &lt;auto-generated /&gt; header.
    /// </summary>
    public bool AddAutoGeneratedHeader { get; init; }

    /// <summary>
    /// Gets a value indicating whether to add the <see cref="EmbeddedAttribute"/> attribute.
    /// </summary>
    public bool AddEmbeddedAttribute { get; init; }

    /// <summary>
    /// Gets a value indicating whether to force global type names.
    /// Predefined keywords and unresolved types are preserved. Imports are retained when
    /// the source cannot be fully bound against the current compilation unless
    /// <see cref="AggressiveImportRemoval"/> is enabled.
    /// </summary>
    public bool RewriteTypeNames { get; init; }

    /// <summary>
    /// Gets a value indicating whether to remove resolvable namespace imports even when the source has binding errors.
    /// Only applies when <see cref="RewriteTypeNames"/> is enabled. Unknown imports and imports
    /// retained for extension methods are preserved, as are aliases, static imports, and global imports.
    /// </summary>
    /// <remarks>
    /// Defaults to false. Enabling this can remove imports needed by unresolved references in the eventual destination.
    /// </remarks>
    public bool AggressiveImportRemoval { get; init; }

    /// <summary>
    /// Gets a value indicating whether to rewrite supported extension invocations as fully qualified static calls.
    /// Enabled by default. Conditional access, method groups, query syntax, and calls that cannot be safely bound
    /// are preserved. Import removal still requires <see cref="RewriteTypeNames"/>.
    /// </summary>
    public bool RewriteExtensionCalls { get; init; }

    /// <inheritdoc/>
    public bool TryTransform(
        ICompressionAttributeInfo attribute,
        Compilation compilation,
        [NotNullWhen(true)] out string? output,
        [NotNullWhen(false)] out DiagnosticInfo? diagnostic,
        CancellationToken cancellationToken)
    {
        if (compilation is null)
        {
            throw new ArgumentNullException(nameof(compilation));
        }

        if (attribute is null || attribute.SourceValue is null || attribute.SourceValue.IsWhiteSpace())
        {
            output = string.Empty;
            diagnostic = null;
            return true;
        }

        if (!RewritePublicToInternal && !AddAutoGeneratedAttribute && !AddAutoGeneratedHeader && !AddEmbeddedAttribute && !RewriteTypeNames && !RewriteExtensionCalls)
        {
            output = attribute.SourceValue;
            diagnostic = null;
            return true;
        }

        cancellationToken.ThrowIfCancellationRequested();

        string source = attribute.SourceValue;
        string lineEnding = source.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        CSharpParseOptions parseOptions = compilation.SyntaxTrees
            .Select(tree => tree.Options)
            .OfType<CSharpParseOptions>()
            .FirstOrDefault() ?? CSharpParseOptions.Default;
        SyntaxTree sourceTree = CSharpSyntaxTree.ParseText(source, parseOptions, cancellationToken: cancellationToken);
        Diagnostic? syntaxError = sourceTree.GetDiagnostics(cancellationToken)
            .FirstOrDefault(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error);
        if (syntaxError is not null)
        {
            output = null;
            diagnostic = new DiagnosticInfo(
                DiagnosticDescriptors.InvalidCSharpTransformerSource,
                attribute.MemberName,
                syntaxError.GetMessage(CultureInfo.InvariantCulture));

            return false;
        }

        // Check if the source tree already exists in the compilation to avoid adding duplicate trees
        SyntaxTree? existingTree = compilation.SyntaxTrees.FirstOrDefault(tree =>
            StringComparer.Ordinal.Equals(tree.GetText(cancellationToken).ToString(), source));
        if (existingTree is not null)
        {
            sourceTree = existingTree;
        }

        // If the source tree is not already part of the compilation, add it to a new compilation for semantic analysis
        Compilation semanticCompilation = existingTree is null ? compilation.AddSyntaxTrees(sourceTree) : compilation;
        SemanticModel semanticModel = semanticCompilation.GetSemanticModel(sourceTree);
        CompilationUnitSyntax root = sourceTree.GetCompilationUnitRoot(cancellationToken);

        if (RewriteExtensionCalls)
        {
            var rewrittenRoot = (CompilationUnitSyntax)new ExtensionCallRewriter(semanticModel, cancellationToken).Visit(root)!;
            if (!ReferenceEquals(root, rewrittenRoot))
            {
                SyntaxTree rewrittenTree = sourceTree.WithRootAndOptions(rewrittenRoot, sourceTree.Options);
                semanticCompilation = semanticCompilation.ReplaceSyntaxTree(sourceTree, rewrittenTree);
                semanticModel = semanticCompilation.GetSemanticModel(rewrittenTree);
                root = rewrittenTree.GetCompilationUnitRoot(cancellationToken);
            }
        }

        if (RewriteTypeNames)
        {
            HashSet<string>? extensionNamespaces = null;

            // AggressiveImportRemoval is enabled or there are no binding errors,
            // collect the namespaces of extension methods to avoid removing their imports later.
            if (AggressiveImportRemoval
                || !semanticModel.GetDiagnostics(cancellationToken: cancellationToken)
                                 .Any(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error))
            {
                extensionNamespaces = GetExtensionNamespaces(root, semanticModel, cancellationToken);
            }

            // Update the syntax tree to use fully qualified type names for all resolvable types
            root = (CompilationUnitSyntax)new GlobalTypeNameRewriter(semanticModel, cancellationToken).Visit(root)!;

            // Remove unused namespace imports if there are no binding errors or if AggressiveImportRemoval is enabled
            if (extensionNamespaces is not null)
            {
                root = RemoveUnusedNamespaceUsings(root, extensionNamespaces, cancellationToken);
            }
        }

        // Transform members to apply public-to-internal conversion and add attributes as needed
        if (RewritePublicToInternal || AddAutoGeneratedAttribute || AddEmbeddedAttribute)
        {
            if (AddAutoGeneratedAttribute || AddEmbeddedAttribute)
            {
                // Preserve semantic identity before member edits detach attributes from this tree.
                SyntaxTree attributeTree = semanticModel.SyntaxTree.WithRootAndOptions(root, semanticModel.SyntaxTree.Options);
                semanticCompilation = semanticCompilation.ReplaceSyntaxTree(semanticModel.SyntaxTree, attributeTree);
                semanticModel = semanticCompilation.GetSemanticModel(attributeTree);
                root = attributeTree.GetCompilationUnitRoot(cancellationToken);
                root = root.ReplaceNodes(root.DescendantNodes().OfType<AttributeSyntax>(), (attribute, _) =>
                {
                    cancellationToken.ThrowIfCancellationRequested();
                    return semanticModel.GetTypeInfo(attribute, cancellationToken).Type is INamedTypeSymbol { TypeKind: not TypeKind.Error } type
                        ? attribute.WithAdditionalAnnotations(new SyntaxAnnotation(ResolvedAttributeTypeAnnotation, type.ToDisplayString()))
                        : attribute;
                });
            }

            AttributeSyntax? generatedCodeAttribute = AddAutoGeneratedAttribute
                ? CreateAttribute(
                    "global::System.CodeDom.Compiler.GeneratedCode",
                    compilation.Assembly.Identity.Name,
                    compilation.Assembly.Identity.Version.ToString())
                : null;
            root = root.WithMembers(TransformMembers(
                root.Members,
                RewritePublicToInternal,
                generatedCodeAttribute,
                AddEmbeddedAttribute,
                lineEnding,
                cancellationToken));
        }

        // Add an <auto-generated /> header if requested and not already present
        if (AddAutoGeneratedHeader && !root.GetLeadingTrivia().ToFullString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase))
        {
            SyntaxTriviaList header = SyntaxFactory.TriviaList(
                SyntaxFactory.Comment("// <auto-generated />"),
                SyntaxFactory.EndOfLine(lineEnding));
            root = root.WithLeadingTrivia(header.AddRange(root.GetLeadingTrivia()));
        }

        output = root.ToFullString();

        diagnostic = null;
        return true;
    }

    private static HashSet<string> GetExtensionNamespaces(
        CompilationUnitSyntax root,
        SemanticModel semanticModel,
        CancellationToken cancellationToken)
    {
        var extensionNamespaces = new HashSet<string>(StringComparer.Ordinal);
        foreach (SyntaxNode node in root.DescendantNodes())
        {
            cancellationToken.ThrowIfCancellationRequested();
            switch (node)
            {
                case MemberAccessExpressionSyntax or MemberBindingExpressionSyntax:
                    SymbolInfo symbolInfo = semanticModel.GetSymbolInfo(node, cancellationToken);
                    if (symbolInfo.Symbol is IMethodSymbol { ReducedFrom: not null } method)
                    {
                        AddMethod(method);
                    }
                    else if (symbolInfo.Symbol is null)
                    {
                        AddSymbols(symbolInfo);
                    }

                    break;
                case QueryClauseSyntax clause:
                    QueryClauseInfo queryInfo = semanticModel.GetQueryClauseInfo(clause, cancellationToken);
                    AddSymbols(queryInfo.CastInfo);
                    AddSymbols(queryInfo.OperationInfo);
                    break;
                case SelectOrGroupClauseSyntax or OrderingSyntax:
                    AddSymbols(semanticModel.GetSymbolInfo(node, cancellationToken));
                    break;
                case CommonForEachStatementSyntax loop:
                    AddMethod(semanticModel.GetForEachStatementInfo(loop).GetEnumeratorMethod);
                    if (loop is ForEachVariableStatementSyntax deconstructionLoop)
                    {
                        AddDeconstruction(semanticModel.GetDeconstructionInfo(deconstructionLoop));
                    }

                    break;
                case AwaitExpressionSyntax awaitExpression:
                    AddMethod(semanticModel.GetAwaitExpressionInfo(awaitExpression).GetAwaiterMethod);
                    break;
                case AssignmentExpressionSyntax assignment when assignment.IsKind(SyntaxKind.SimpleAssignmentExpression):
                    AddDeconstruction(semanticModel.GetDeconstructionInfo(assignment));
                    break;
            }
        }

        return extensionNamespaces;

        void AddMethod(IMethodSymbol? method)
        {
            if (method is null)
            {
                return;
            }

            IMethodSymbol definition = method.ReducedFrom ?? method;
            if (definition.IsExtensionMethod)
            {
                _ = extensionNamespaces.Add(definition.ContainingNamespace.ToDisplayString());
            }
        }

        void AddSymbols(SymbolInfo info)
        {
            AddMethod(info.Symbol as IMethodSymbol);
            foreach (ISymbol candidate in info.CandidateSymbols)
            {
                AddMethod(candidate as IMethodSymbol);
            }
        }

        void AddDeconstruction(DeconstructionInfo info)
        {
            cancellationToken.ThrowIfCancellationRequested();
            AddMethod(info.Method);
            foreach (DeconstructionInfo nested in info.Nested)
            {
                AddDeconstruction(nested);
            }
        }
    }

    private static CompilationUnitSyntax RemoveUnusedNamespaceUsings(
        CompilationUnitSyntax root,
        HashSet<string> extensionNamespaces,
        CancellationToken cancellationToken)
    {
        var unusedImports = new List<UsingDirectiveSyntax>();
        foreach (UsingDirectiveSyntax node in root.DescendantNodes().OfType<UsingDirectiveSyntax>())
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (node.GlobalKeyword.IsKind(SyntaxKind.GlobalKeyword)
                || node.StaticKeyword.IsKind(SyntaxKind.StaticKeyword)
                || node.Alias is not null)
            {
                continue;
            }

            string? namespaceName = node.GetAnnotations(GlobalTypeNameRewriter.ResolvableImport).SingleOrDefault()?.Data;
            if (namespaceName is not null && !extensionNamespaces.Contains(namespaceName))
            {
                unusedImports.Add(node);
            }
        }

        return root.RemoveNodes(unusedImports, SyntaxRemoveOptions.KeepExteriorTrivia)!;
    }

    private static SyntaxList<MemberDeclarationSyntax> TransformMembers(
        SyntaxList<MemberDeclarationSyntax> members,
        bool publicToInternal,
        AttributeSyntax? generatedCodeAttribute,
        bool addEmbeddedAttribute,
        string lineEnding,
        CancellationToken cancellationToken)
    {
        var transformed = new List<MemberDeclarationSyntax>(members.Count);
        foreach (MemberDeclarationSyntax member in members)
        {
            cancellationToken.ThrowIfCancellationRequested();
            transformed.Add(TransformMember(member, publicToInternal, generatedCodeAttribute, addEmbeddedAttribute, lineEnding, cancellationToken));
        }

        return SyntaxFactory.List(transformed);
    }

    private static MemberDeclarationSyntax TransformMember(
        MemberDeclarationSyntax member,
        bool publicToInternal,
        AttributeSyntax? generatedCodeAttribute,
        bool addEmbeddedAttribute,
        string lineEnding,
        CancellationToken cancellationToken)
        => member switch
        {
            BaseTypeDeclarationSyntax declaration => TransformTypeDeclaration(
                declaration, publicToInternal, generatedCodeAttribute, addEmbeddedAttribute, lineEnding, cancellationToken),
            DelegateDeclarationSyntax declaration => declaration
                .WithModifiers(publicToInternal ? MakeInternal(declaration.Modifiers) : declaration.Modifiers)
                .WithAttributeLists(AddAttributes(declaration.AttributeLists, generatedCodeAttribute, addEmbeddedAttribute, lineEnding)),
            NamespaceDeclarationSyntax declaration => declaration.WithMembers(TransformMembers(
                declaration.Members, publicToInternal, generatedCodeAttribute, addEmbeddedAttribute, lineEnding, cancellationToken)),
            FileScopedNamespaceDeclarationSyntax declaration => declaration.WithMembers(TransformMembers(
                declaration.Members, publicToInternal, generatedCodeAttribute, addEmbeddedAttribute, lineEnding, cancellationToken)),
            _ => member,
        };

    private static MemberDeclarationSyntax TransformTypeDeclaration(
        BaseTypeDeclarationSyntax declaration,
        bool publicToInternal,
        AttributeSyntax? generatedCodeAttribute,
        bool addEmbeddedAttribute,
        string lineEnding,
        CancellationToken cancellationToken)
    {
        SyntaxTokenList modifiers = publicToInternal ? MakeInternal(declaration.Modifiers) : declaration.Modifiers;
        SyntaxList<AttributeListSyntax> attributes = AddAttributes(
            declaration.AttributeLists, generatedCodeAttribute, addEmbeddedAttribute, lineEnding);

        // Recursively transform nested members for classes, structs, and interfaces
        if (declaration is TypeDeclarationSyntax typeDeclaration)
        {
            return typeDeclaration
                .WithModifiers(modifiers)
                .WithAttributeLists(attributes)
                .WithMembers(TransformMembers(
                    typeDeclaration.Members,
                    publicToInternal: false,
                    generatedCodeAttribute,
                    addEmbeddedAttribute,
                    lineEnding,
                    cancellationToken));
        }

        // For enums, just update the modifiers and attributes
        return declaration.WithModifiers(modifiers).WithAttributeLists(attributes);
    }

    private static SyntaxList<AttributeListSyntax> AddAttributes(
        SyntaxList<AttributeListSyntax> attributeLists,
        AttributeSyntax? generatedCodeAttribute,
        bool addEmbeddedAttribute,
        string lineEnding)
    {
        bool hasGeneratedCodeAttribute = generatedCodeAttribute is null || HasAttribute(attributeLists, "System.CodeDom.Compiler.GeneratedCodeAttribute");
        bool hasEmbeddedAttribute = !addEmbeddedAttribute || HasAttribute(attributeLists, "Microsoft.CodeAnalysis.EmbeddedAttribute");
        if (hasGeneratedCodeAttribute && hasEmbeddedAttribute)
        {
            return attributeLists;
        }

        var attributes = new List<AttributeSyntax>();
        if (!hasGeneratedCodeAttribute)
        {
            attributes.Add(generatedCodeAttribute!);
        }

        if (!hasEmbeddedAttribute)
        {
            attributes.Add(CreateAttribute("global::Microsoft.CodeAnalysis.Embedded"));
        }

        AttributeListSyntax addedAttributes = SyntaxFactory.AttributeList(SyntaxFactory.SeparatedList(attributes))
            .WithTrailingTrivia(SyntaxFactory.EndOfLine(lineEnding));
        return attributeLists.Add(addedAttributes);
    }

    private static AttributeSyntax CreateAttribute(string name, params string[] arguments)
        => SyntaxFactory.Attribute(
            SyntaxFactory.ParseName(name),
            arguments.Length == 0
                ? null
                : SyntaxFactory.AttributeArgumentList(SyntaxFactory.SeparatedList(arguments.Select(argument =>
                    SyntaxFactory.AttributeArgument(SyntaxFactory.LiteralExpression(
                        SyntaxKind.StringLiteralExpression,
                        SyntaxFactory.Literal(argument)))))));

    private static bool HasAttribute(SyntaxList<AttributeListSyntax> attributeLists, string attributeName)
        => attributeLists.SelectMany(list => list.Attributes).Any(attribute =>
        {
            string? resolvedName = attribute.GetAnnotations(ResolvedAttributeTypeAnnotation).SingleOrDefault()?.Data;
            if (resolvedName is not null)
            {
                return resolvedName.Equals(attributeName, StringComparison.Ordinal);
            }

            string name = attribute.Name.ToString();
            if (name.StartsWith("global::", StringComparison.Ordinal))
            {
                name = name["global::".Length..];
            }

            return name.Equals(attributeName, StringComparison.Ordinal)
                || (name + "Attribute").Equals(attributeName, StringComparison.Ordinal);
        });

    private static SyntaxTokenList MakeInternal(SyntaxTokenList modifiers)
    {
        foreach (SyntaxToken modifier in modifiers)
        {
            if (modifier.IsKind(SyntaxKind.PublicKeyword))
            {
                return modifiers.Replace(
                    modifier,
                    SyntaxFactory.Token(modifier.LeadingTrivia, SyntaxKind.InternalKeyword, modifier.TrailingTrivia));
            }
        }

        return modifiers;
    }

    private sealed class ExtensionCallRewriter(SemanticModel semanticModel, CancellationToken cancellationToken) : CSharpSyntaxRewriter
    {
        public override SyntaxNode? VisitInvocationExpression(InvocationExpressionSyntax node)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var visited = (InvocationExpressionSyntax)base.VisitInvocationExpression(node)!;
            if (node.Expression is not MemberAccessExpressionSyntax
                || visited.Expression is not MemberAccessExpressionSyntax memberAccess
                || node.ContainsDirectives
                || node.Ancestors().Any(ancestor => ancestor is ConditionalAccessExpressionSyntax or QueryExpressionSyntax)
                || semanticModel.GetSymbolInfo(node, cancellationToken).Symbol is not IMethodSymbol method
                || method.ReducedFrom is not IMethodSymbol extensionMethod
                || method.TypeArguments.Any(type => !CanNameType(type)))
            {
                return visited;
            }

            SimpleNameSyntax methodName = memberAccess.Name;
            if (method.IsGenericMethod && methodName is not GenericNameSyntax)
            {
                methodName = SyntaxFactory.GenericName(
                    memberAccess.Name.Identifier,
                    SyntaxFactory.TypeArgumentList(SyntaxFactory.SeparatedList(method.TypeArguments.Select(type =>
                        SyntaxFactory.ParseTypeName(type.ToDisplayString(FullyQualifiedTypeFormat))))));
            }

            MemberAccessExpressionSyntax target = SyntaxFactory.MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                SyntaxFactory.ParseExpression(extensionMethod.ContainingType.ToDisplayString(FullyQualifiedTypeFormat)),
                methodName).WithOperatorToken(memberAccess.OperatorToken);
            ArgumentSyntax receiver = SyntaxFactory.Argument(memberAccess.Expression.WithoutLeadingTrivia());
            if (extensionMethod.Parameters[0].RefKind == RefKind.Ref)
            {
                receiver = receiver.WithRefKindKeyword(SyntaxFactory.Token(SyntaxKind.RefKeyword).WithTrailingTrivia(SyntaxFactory.Space));
            }

            InvocationExpressionSyntax rewritten = visited
                .WithExpression(target)
                .WithArgumentList(visited.ArgumentList.WithArguments(visited.ArgumentList.Arguments.Insert(0, receiver)))
                .WithTriviaFrom(node);

            // Static overload resolution must select the same constructed method, not just a method with the same name.
            return semanticModel.GetSpeculativeSymbolInfo(node.SpanStart, rewritten, SpeculativeBindingOption.BindAsExpression).Symbol is not IMethodSymbol bound
                || !SymbolEqualityComparer.Default.Equals(bound.OriginalDefinition, extensionMethod.OriginalDefinition)
                || !Enumerable.SequenceEqual(bound.TypeArguments, method.TypeArguments, SymbolEqualityComparer.Default)
                ? visited
                : rewritten;
        }

        private static bool CanNameType(ITypeSymbol type)
            => type switch
            {
                IErrorTypeSymbol => false,
                IArrayTypeSymbol array => CanNameType(array.ElementType),
                IPointerTypeSymbol pointer => CanNameType(pointer.PointedAtType),
                INamedTypeSymbol named => !named.IsAnonymousType && named.TypeArguments.All(CanNameType)
                    && (named.ContainingType is null || CanNameType(named.ContainingType)),
                _ => true,
            };
    }

    /// <summary>
    /// Goes through the syntax tree and replaces all resolvable type names with their fully qualified names.
    /// </summary>
    /// <param name="semanticModel">The semantic model to use for symbol resolution.</param>
    /// <param name="cancellationToken">A cancellation token.</param>
    private sealed class GlobalTypeNameRewriter(SemanticModel semanticModel, CancellationToken cancellationToken) : CSharpSyntaxRewriter
    {
        internal const string ResolvableImport = "CSharpRewriter.ResolvableImport";

        public override SyntaxNode? VisitAttribute(AttributeSyntax node)
        {
            cancellationToken.ThrowIfCancellationRequested();
            return !IsAliasQualified(node.Name)
                && semanticModel.GetTypeInfo(node, cancellationToken).Type is INamedTypeSymbol type
                && !ContainsUnresolvedType(type)
                    ? node.WithName(SyntaxFactory.ParseName(GetFullyQualifiedName(type)).WithTriviaFrom(node.Name))
                          .WithArgumentList((AttributeArgumentListSyntax?)Visit(node.ArgumentList))
                    : base.VisitAttribute(node);
        }

        public override SyntaxNode? VisitUsingDirective(UsingDirectiveSyntax node)
        {
            cancellationToken.ThrowIfCancellationRequested();
            return node.Name is not null && semanticModel.GetSymbolInfo(node.Name, cancellationToken).Symbol is INamespaceSymbol namespaceSymbol
                ? node.WithAdditionalAnnotations(new SyntaxAnnotation(ResolvableImport, namespaceSymbol.ToDisplayString()))
                : node;
        }

        public override SyntaxNode? VisitMemberAccessExpression(MemberAccessExpressionSyntax node)
        {
            cancellationToken.ThrowIfCancellationRequested();

            return !IsAliasQualified(node)
                && semanticModel.GetSymbolInfo(node, cancellationToken).Symbol is INamedTypeSymbol namedType
                && !ContainsUnresolvedType(namedType)
                    ? SyntaxFactory.ParseExpression(GetFullyQualifiedName(namedType)).WithTriviaFrom(node)
                    : base.VisitMemberAccessExpression(node);
        }

        public override SyntaxNode? Visit(SyntaxNode? node)
        {
            if (node is not NameSyntax name)
            {
                return base.Visit(node);
            }

            cancellationToken.ThrowIfCancellationRequested();

            // Deconstruction var describes the whole designation, not a replaceable tuple type.
            if (name.IsVar && name.Parent is DeclarationExpressionSyntax { Designation: ParenthesizedVariableDesignationSyntax })
            {
                return node;
            }

            // Preserve alias-qualified names, but still visit their generic type arguments.
            if (IsAliasQualified(name)
                || (name.Parent is QualifiedNameSyntax qualifiedName && qualifiedName.Right == name && IsAliasQualified(qualifiedName))
                || (name.Parent is AliasQualifiedNameSyntax aliasName && aliasName.Name == name && IsAliasQualified(aliasName)))
            {
                return base.Visit(node);
            }

            // The right side must remain a SimpleNameSyntax; qualify its containing expression instead.
            if (name.Parent is MemberAccessExpressionSyntax memberAccess && memberAccess.Name == name)
            {
                return base.Visit(node);
            }

            ISymbol? symbol = semanticModel.GetSymbolInfo(name, cancellationToken).Symbol;
            var namedType = symbol as INamedTypeSymbol;
            if (namedType is null && IsTypeContext(name))
            {
                namedType = semanticModel.GetTypeInfo(name, cancellationToken).Type as INamedTypeSymbol;
            }

            if (namedType is null || namedType.IsAnonymousType || ContainsUnresolvedType(namedType))
            {
                return base.Visit(node);
            }

            string fullyQualifiedName = GetFullyQualifiedName(namedType);
            return IsExpressionContext(name)
                ? SyntaxFactory.ParseExpression(fullyQualifiedName).WithTriviaFrom(name)
                : SyntaxFactory.ParseTypeName(fullyQualifiedName).WithTriviaFrom(name);
        }

        private static string GetFullyQualifiedName(INamedTypeSymbol namedType)
            => namedType.ToDisplayString(namedType.SpecialType is SpecialType.None
                ? FullyQualifiedTypeFormat
                : FullyQualifiedTypeFormatWithoutSpecialTypes);

        private static bool ContainsUnresolvedType(ITypeSymbol type)
            => type switch
            {
                IErrorTypeSymbol => true,
                IArrayTypeSymbol array => ContainsUnresolvedType(array.ElementType),
                IPointerTypeSymbol pointer => ContainsUnresolvedType(pointer.PointedAtType),
                INamedTypeSymbol named => named.TypeArguments.Any(ContainsUnresolvedType)
                    || (named.ContainingType is not null && ContainsUnresolvedType(named.ContainingType)),
                _ => false,
            };

        private static bool IsTypeContext(NameSyntax name)
            => name.Parent switch
            {
                VariableDeclarationSyntax declaration => declaration.Type == name,
                PropertyDeclarationSyntax declaration => declaration.Type == name,
                EventDeclarationSyntax declaration => declaration.Type == name,
                MethodDeclarationSyntax declaration => declaration.ReturnType == name,
                DelegateDeclarationSyntax declaration => declaration.ReturnType == name,
                ParameterSyntax declaration => declaration.Type == name,
                ObjectCreationExpressionSyntax expression => expression.Type == name,
                TypeOfExpressionSyntax expression => expression.Type == name,
                DefaultExpressionSyntax expression => expression.Type == name,
                CastExpressionSyntax expression => expression.Type == name,
                SizeOfExpressionSyntax expression => expression.Type == name,
                SimpleBaseTypeSyntax baseType => baseType.Type == name,
                TypeConstraintSyntax constraint => constraint.Type == name,
                TypeArgumentListSyntax => true,
                ArrayTypeSyntax => true,
                NullableTypeSyntax => true,
                PointerTypeSyntax => true,
                RefTypeSyntax => true,
                TupleElementSyntax => true,
                _ => name.Parent is TypeSyntax,
            };

        private static bool IsExpressionContext(NameSyntax name)
            => name.Parent switch
            {
                MemberAccessExpressionSyntax memberAccess => memberAccess.Expression == name,
                ArgumentSyntax argument => argument.Expression == name,
                InvocationExpressionSyntax invocation => invocation.Expression == name,
                _ => false,
            };

        private bool IsAliasQualified(SyntaxNode node)
            => node switch
            {
                IdentifierNameSyntax identifier => semanticModel.GetAliasInfo(identifier, cancellationToken) is not null,
                QualifiedNameSyntax qualified => IsAliasQualified(qualified.Left),
                AliasQualifiedNameSyntax qualified => IsAliasQualified(qualified.Alias),
                MemberAccessExpressionSyntax access => IsAliasQualified(access.Expression),
                _ => false,
            };
    }
}
