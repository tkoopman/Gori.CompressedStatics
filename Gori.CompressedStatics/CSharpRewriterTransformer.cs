using System.Collections.Immutable;
using System.Diagnostics.CodeAnalysis;

using Gori.CompressedStatics.CSharp;
using Gori.CompressedStatics.Generators;

using Microsoft.CodeAnalysis;

namespace Gori.CompressedStatics;

/// <summary>
/// Input transformer that can edit C# code ready for use in source generators.
/// </summary>
public class CSharpRewriterTransformer : IStringCompilationTransformer
{
    /// <summary>
    /// Default instance.
    /// </summary>
    public static readonly CSharpRewriterTransformer Instance = new CSharpRewriterTransformer(CSharpRewriterOptions.Default);

    /// <summary>
    /// Initializes a new instance of the <see cref="CSharpRewriterTransformer"/> class
    /// with <see cref="CSharpRewriterOptions.Default"/> options.
    /// </summary>
    public CSharpRewriterTransformer()
        : this(CSharpRewriterOptions.Default)
    {
    }

    /// <summary>
    /// Initializes a new instance of the <see cref="CSharpRewriterTransformer"/> class with the selected options.
    /// </summary>
    /// <param name="options">The exact set of transformations to enable.</param>
    public CSharpRewriterTransformer(CSharpRewriterOptions options)
    {
        if ((options & ~CSharpRewriterOptions.All) != 0)
        {
            throw new ArgumentOutOfRangeException(nameof(options), options, "Unknown C# rewriter option flags.");
        }

        RewritePublicToInternal = (options & CSharpRewriterOptions.RewritePublicToInternal) != 0;
        AddAutoGeneratedAttribute = (options & CSharpRewriterOptions.AddAutoGeneratedAttribute) != 0;
        AddAutoGeneratedHeader = (options & CSharpRewriterOptions.AddAutoGeneratedHeader) != 0;
        AddEmbeddedAttribute = (options & CSharpRewriterOptions.AddEmbeddedAttribute) != 0;
        AddGlobalUsings = (options & CSharpRewriterOptions.AddGlobalUsings) != 0;
        AddNullableDirective = (options & CSharpRewriterOptions.AddNullableDirective) != 0;
        RewriteTypeNames = (options & CSharpRewriterOptions.RewriteTypeNames) != 0;
        AggressiveImportRemoval = (options & CSharpRewriterOptions.AggressiveImportRemoval) != 0;
        RewriteExtensionCalls = (options & CSharpRewriterOptions.RewriteExtensionCalls) != 0;
    }

    /// <summary>
    /// Gets a value indicating whether to change any public type to internal.
    /// NOTE: Only changes top-level types, nested types are not affected.
    /// </summary>
    public bool RewritePublicToInternal { get; init; }

    /// <summary>
    /// Gets a value indicating whether to add the <see cref="System.CodeDom.Compiler.GeneratedCodeAttribute"/> attribute
    /// using the consuming compilation's assembly name and assembly version.
    /// </summary>
    public bool AddAutoGeneratedAttribute { get; init; }

    /// <summary>
    /// Gets a value indicating whether to add &lt;auto-generated /&gt; header.
    /// </summary>
    public bool AddAutoGeneratedHeader { get; init; }

    /// <summary>
    /// Gets a value indicating whether to add the <see cref="EmbeddedAttribute"/> attribute.
    /// </summary>
    public bool AddEmbeddedAttribute { get; init; }

    /// <summary>
    /// Gets a value indicating whether to add compilation global usings used by the source as ordinary file-level usings.
    /// </summary>
    public bool AddGlobalUsings { get; init; }

    /// <summary>
    /// Gets a value indicating whether to add <c>#nullable enable</c> when nullable property types are present
    /// and the source has no nullable directive.
    /// </summary>
    public bool AddNullableDirective { get; init; }

    /// <summary>
    /// Gets a value indicating whether to force global type names.
    /// Predefined keywords and unresolved types are preserved. Imports are retained when
    /// the source cannot be fully bound against the current compilation unless
    /// <see cref="AggressiveImportRemoval"/> is enabled.
    /// </summary>
    public bool RewriteTypeNames { get; init; }

    /// <summary>
    /// Gets a value indicating whether to remove resolvable namespace imports even when the source has binding errors.
    /// Only applies when <see cref="RewriteTypeNames"/> is enabled. Unknown imports and imports
    /// retained for extension methods are preserved, as are aliases, static imports, and global imports.
    /// </summary>
    /// <remarks>
    /// Defaults to false. Enabling this can remove imports needed by unresolved references in the eventual destination.
    /// </remarks>
    public bool AggressiveImportRemoval { get; init; }

    /// <summary>
    /// Gets a value indicating whether to rewrite supported extension invocations as fully qualified static calls.
    /// Enabled by default. Conditional access, method groups, query syntax, and calls that cannot be safely bound
    /// are preserved. Import removal still requires <see cref="RewriteTypeNames"/>.
    /// </summary>
    public bool RewriteExtensionCalls { get; init; }

    /// <inheritdoc/>
    public bool TryTransform(
        ICompressionAttributeInfo attribute,
        Compilation compilation,
        [NotNullWhen(true)] out string? output,
        out ImmutableArray<DiagnosticInfo> diagnostics,
        CancellationToken cancellationToken)
    {
        if (compilation is null)
        {
            throw new ArgumentNullException(nameof(compilation));
        }

        if (attribute is null || attribute.SourceValue is null)
        {
            output = string.Empty;
            diagnostics = default;
            return true;
        }

        RewriterConfiguration configuration = CSharpRewriterConfigurationReader.Load(
            compilation, out IEnumerable<RewriteIssue> assemblyIssues, cancellationToken);

        var rewriter = new CSharpRewriter
        {
            RewritePublicToInternal = RewritePublicToInternal,
            AddAutoGeneratedAttribute = AddAutoGeneratedAttribute,
            AddAutoGeneratedHeader = AddAutoGeneratedHeader,
            AddEmbeddedAttribute = AddEmbeddedAttribute,
            AddGlobalUsings = AddGlobalUsings,
            AddNullableDirective = AddNullableDirective,
            RewriteTypeNames = RewriteTypeNames,
            AggressiveImportRemoval = AggressiveImportRemoval,
            RewriteExtensionCalls = RewriteExtensionCalls,
            Configuration = configuration,
        };

        try
        {
            output = rewriter.Rewrite(attribute.SourceValue, compilation, out IEnumerable<RewriteIssue> issues, cancellationToken);
            diagnostics = [.. assemblyIssues.Concat(issues).Select(issue => ToDiagnosticInfo(issue, attribute.MemberName))];
            return true;
        }
        catch (CSharpRewriterInvalidSourceException exception)
        {
            output = null;
            diagnostics = [
                .. assemblyIssues.Select(issue => ToDiagnosticInfo(issue, attribute.MemberName)),
                new DiagnosticInfo(
                    DiagnosticDescriptors.InvalidCSharpTransformerSource,
                    attribute.MemberName,
                    exception.Message),
            ];
            return false;
        }
    }

    private static DiagnosticInfo ToDiagnosticInfo(RewriteIssue issue, string memberName)
    {
        string sourceLocationSuffix = GetSourceLocationSuffix(issue.Location);
        return issue switch
        {
            BindingIssue bindingIssue => new DiagnosticInfo(
                DiagnosticDescriptors.CSharpRewriterBindingIssue,
                memberName,
                bindingIssue.DiagnosticID,
                bindingIssue.Message,
                sourceLocationSuffix)
            {
                Properties = ImmutableDictionary<string, string?>.Empty
                    .Add("CompilerDiagnosticId", bindingIssue.DiagnosticID)
                    .Add("CompilerDiagnosticMessage", bindingIssue.Message),
            },

            InvalidConfiguration invalidConfiguration when invalidConfiguration.Reason == InvalidConfigurationReason.ConflictingRules
                => new DiagnosticInfo(
                    DiagnosticDescriptors.CSharpRewriterConflictingConfiguration,
                    invalidConfiguration.Value ?? "<null>",
                    sourceLocationSuffix),

            InvalidConfiguration invalidConfiguration => new DiagnosticInfo(
                DiagnosticDescriptors.CSharpRewriterInvalidConfiguration,
                DescribeConfigurationIssue(invalidConfiguration),
                sourceLocationSuffix),

            MappingIgnoreOverlap mappingIgnoreOverlap => new DiagnosticInfo(
                DiagnosticDescriptors.CSharpRewriterMappingIgnoreOverlap,
                mappingIgnoreOverlap.Reference,
                mappingIgnoreOverlap.Destination,
                mappingIgnoreOverlap.DiagnosticID,
                mappingIgnoreOverlap.MessageContains ?? "<any message>",
                sourceLocationSuffix),

            Unresolvable unresolvable => new DiagnosticInfo(
                DiagnosticDescriptors.CSharpRewriterUnresolvable,
                memberName,
                unresolvable.Type switch
                {
                    UnresolvableType.UnresolvableType => "type",
                    UnresolvableType.AmbiguousType => "ambiguous type",
                    UnresolvableType.UnresolvableExtension => "extension method",
                    _ => unresolvable.Type.ToString(),
                },
                unresolvable.Name,
                sourceLocationSuffix)
            {
                Properties = ImmutableDictionary<string, string?>.Empty
                    .Add("UnresolvableType", unresolvable.Type.ToString())
                    .Add("UnresolvableName", unresolvable.Name),
            },

            _ => throw new InvalidOperationException($"Unexpected issue type: {issue.GetType().FullName ?? issue.GetType().Name}"),
        };
    }

    private static string GetSourceLocationSuffix(Location? location)
    {
        if (location is { IsInSource: true })
        {
            FileLinePositionSpan lineSpan = location.GetLineSpan();
            Microsoft.CodeAnalysis.Text.LinePosition start = lineSpan.StartLinePosition;
            string sourceLocation = string.IsNullOrEmpty(lineSpan.Path)
                ? $"line {start.Line + 1}, column {start.Character + 1}"
                : $"{lineSpan.Path}({start.Line + 1},{start.Character + 1})";

            return $" (source location: {sourceLocation})";
        }

        return string.Empty;
    }

    private static string DescribeConfigurationIssue(InvalidConfiguration issue)
    {
        string description = issue.Reason switch
        {
            InvalidConfigurationReason.InvalidValue => issue.Message ?? "A configuration value is invalid.",
            InvalidConfigurationReason.UnsupportedContainingTypeArguments =>
                $"Mapping '{issue.Value ?? "<null>"}' cannot preserve generic arguments on containing types; map the outer type instead.",
            _ => $"Configuration is invalid ({issue.Reason}).",
        };

        if (issue.ArgumentName is not null && !issue.ArgumentName.IsWhiteSpace())
        {
            description += $" Argument: {issue.ArgumentName}.";
        }

        if (issue.ArgumentIndex is int index)
        {
            description += $" Array element: {index}.";
        }

        if (issue.ArgumentValue is not null)
        {
            description += $" Value: '{issue.ArgumentValue}'.";
        }

        return description;
    }
}
