using System.Globalization;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Gori.CompressedStatics.CSharp;

/// <summary>
/// Configuration to use when rewriting.
/// </summary>
public sealed partial class CSharpRewriter
{
    /// <summary>
    /// Gets a value indicating whether to change any public type to internal.
    /// NOTE: Only changes top-level types, nested types are not affected.
    /// </summary>
    public bool RewritePublicToInternal { get; init; } = true;

    /// <summary>
    /// Gets a value indicating whether to add the <see cref="System.CodeDom.Compiler.GeneratedCodeAttribute"/> attribute
    /// using the consuming compilation's assembly name and assembly version.
    /// NOTE: Only changes top-level types, nested types are not affected.
    /// </summary>
    public bool AddAutoGeneratedAttribute { get; init; } = true;

    /// <summary>
    /// Gets a value indicating whether to add &lt;auto-generated /&gt; header.
    /// </summary>
    public bool AddAutoGeneratedHeader { get; init; } = true;

    /// <summary>
    /// Gets a value indicating whether to add the <see cref="EmbeddedAttribute"/> attribute.
    /// NOTE: Only changes top-level types, nested types are not affected.
    /// </summary>
    public bool AddEmbeddedAttribute { get; init; } = true;

    /// <summary>
    /// Gets a value indicating whether to add compilation global usings used by the source as ordinary file-level usings.
    /// </summary>
    public bool AddGlobalUsings { get; init; } = true;

    /// <summary>
    /// Gets a value indicating whether to add <c>#nullable enable</c> when nullable property types are present
    /// and the source has no nullable directive.
    /// </summary>
    public bool AddNullableDirective { get; init; } = true;

    /// <summary>
    /// Gets a value indicating whether to force global type names.
    /// Predefined keywords and unresolved types are preserved. Imports are retained when
    /// the source cannot be fully bound against the current compilation unless
    /// <see cref="AggressiveImportRemoval"/> is enabled.
    /// </summary>
    public bool RewriteTypeNames { get; init; } = true;

    /// <summary>
    /// Gets a value indicating whether to remove resolvable namespace imports even when the source has binding errors.
    /// Only applies when <see cref="RewriteTypeNames"/> is enabled. Unknown imports and imports
    /// retained for extension methods are preserved, as are aliases, static imports, and global imports.
    /// </summary>
    /// <remarks>
    /// Defaults to false. Enabling this can remove imports needed by unresolved references in the eventual destination.
    /// </remarks>
    public bool AggressiveImportRemoval { get; init; }

    /// <summary>
    /// Gets a value indicating whether to rewrite supported extension invocations as fully qualified static calls.
    /// Enabled by default. Conditional access, method groups, query syntax, and calls that cannot be safely bound
    /// are preserved. Import removal still requires <see cref="RewriteTypeNames"/>.
    /// </summary>
    public bool RewriteExtensionCalls { get; init; } = true;

    /// <summary>
    /// Gets the explicitly supplied rewriter rules.
    /// Null means no configuration. Attributes in the compilation or rewritten source are not loaded automatically.
    /// </summary>
    public RewriterConfiguration? Configuration { get; init; }

    /// <summary>
    /// Perform rewrite of source code using provided compilation for getting semantic model.
    /// </summary>
    /// <param name="sourceCode">The source code to rewrite.</param>
    /// <param name="compilation">The compilation used to get the semantic model.</param>
    /// <param name="issues">The issues encountered during rewriting.</param>
    /// <param name="cancellationToken">The cancellation token.</param>
    /// <returns>The rewritten source code.</returns>
    /// <exception cref="ArgumentNullException">Compilation is null.</exception>
    /// <exception cref="CSharpRewriterInvalidSourceException">Provided source contains syntax errors.</exception>
    public string Rewrite(
        string sourceCode,
        Compilation compilation,
        out IEnumerable<RewriteIssue> issues,
        CancellationToken cancellationToken)
    {
        List<RewriteIssue> issueList = [];
        issues = issueList;

        if (compilation is null)
        {
            throw new ArgumentNullException(nameof(compilation));
        }

        if (sourceCode is null || sourceCode.IsWhiteSpace())
        {
            return string.Empty;
        }

        cancellationToken.ThrowIfCancellationRequested();

        string lineEnding = sourceCode.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        CSharpParseOptions parseOptions = compilation.SyntaxTrees
            .Select(tree => tree.Options)
            .OfType<CSharpParseOptions>()
            .FirstOrDefault() ?? CSharpParseOptions.Default;
        SyntaxTree sourceTree = CSharpSyntaxTree.ParseText(sourceCode, parseOptions, cancellationToken: cancellationToken);
        Diagnostic? syntaxError = sourceTree.GetDiagnostics(cancellationToken)
            .FirstOrDefault(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error);
        if (syntaxError is not null)
        {
            throw new CSharpRewriterInvalidSourceException(syntaxError.GetMessage(CultureInfo.InvariantCulture));
        }

        // Check if the source tree already exists in the compilation to avoid adding duplicate trees
        SyntaxTree? existingTree = compilation.SyntaxTrees.FirstOrDefault(tree =>
            StringComparer.Ordinal.Equals(tree.GetText(cancellationToken).ToString(), sourceCode));
        if (existingTree is not null)
        {
            sourceTree = existingTree;
        }

        // If the source tree is not already part of the compilation, add it to a new compilation for semantic analysis
        Compilation semanticCompilation = existingTree is null ? compilation.AddSyntaxTrees(sourceTree) : compilation;
        SemanticModel semanticModel = semanticCompilation.GetSemanticModel(sourceTree);
        CompilationUnitSyntax root = sourceTree.GetCompilationUnitRoot(cancellationToken);

        var scopedRewriter = new ScopedRewriter(this, compilation, semanticModel, root, issueList, cancellationToken);
        var rewrittenRoot = (CompilationUnitSyntax)scopedRewriter.Visit(root)!;
        if (!ReferenceEquals(root, rewrittenRoot))
        {
            sourceTree = sourceTree.WithRootAndOptions(rewrittenRoot, sourceTree.Options);
            semanticCompilation = semanticCompilation.ReplaceSyntaxTree(semanticModel.SyntaxTree, sourceTree);
            semanticModel = semanticCompilation.GetSemanticModel(sourceTree);
            root = sourceTree.GetCompilationUnitRoot(cancellationToken);
        }

        bool blocksImports = scopedRewriter.ReportBindingIssues();

        HashSet<string>? extensionNamespaces = null;
        if (AddGlobalUsings)
        {
            extensionNamespaces = GetExtensionNamespaces(root, semanticModel, cancellationToken);
            root = AddRequiredGlobalUsings(root, semanticModel, compilation, extensionNamespaces, cancellationToken);
            sourceTree = sourceTree.WithRootAndOptions(root, sourceTree.Options);
            semanticCompilation = semanticCompilation.ReplaceSyntaxTree(semanticModel.SyntaxTree, sourceTree);
            semanticModel = semanticCompilation.GetSemanticModel(sourceTree);
            root = sourceTree.GetCompilationUnitRoot(cancellationToken);
        }

        if (RewriteTypeNames && (AggressiveImportRemoval || !blocksImports))
        {
            extensionNamespaces ??= GetExtensionNamespaces(root, semanticModel, cancellationToken);
            root = RemoveUnusedNamespaceUsings(root, extensionNamespaces, cancellationToken);
        }

        SyntaxTriviaList leadingTrivia = root.GetLeadingTrivia();
        if (AddAutoGeneratedHeader && !leadingTrivia.ToFullString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase))
        {
            SyntaxTriviaList header = SyntaxFactory.TriviaList(
                SyntaxFactory.Comment(Const.AutoGeneratedHeader),
                SyntaxFactory.EndOfLine(lineEnding));
            leadingTrivia = header.AddRange(leadingTrivia);
        }

        if (AddNullableDirective
            && !root.DescendantTrivia(descendIntoTrivia: true).Any(trivia => trivia.IsKind(SyntaxKind.NullableDirectiveTrivia))
            && root.DescendantNodes().Any(node => node switch
            {
                PropertyDeclarationSyntax property => HasNullableType(property.Type),
                IndexerDeclarationSyntax indexer => HasNullableType(indexer.Type),
                _ => false,
            }))
        {
            int insertionIndex = 0;
            for (int index = 0; index < leadingTrivia.Count; index++)
            {
                if (!leadingTrivia[index].ToFullString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                insertionIndex = index + 1;
                if (insertionIndex < leadingTrivia.Count && leadingTrivia[insertionIndex].IsKind(SyntaxKind.EndOfLineTrivia))
                {
                    insertionIndex++;
                }

                break;
            }

            SyntaxTriviaList nullableDirective = SyntaxFactory.ParseLeadingTrivia($"{Const.NullableDirective}{lineEnding}");
            leadingTrivia = leadingTrivia.InsertRange(insertionIndex, nullableDirective);
        }

        root = root.WithLeadingTrivia(leadingTrivia);
        return root.ToFullString();

        static bool HasNullableType(TypeSyntax type)
            => type.DescendantNodesAndSelf().OfType<NullableTypeSyntax>().Any();
    }

    /// <summary>
    /// Checks equality to another CSharpRewriter.
    /// </summary>
    /// <param name="other">The other CSharpRewriter to compare to.</param>
    /// <returns>True if both are equal.</returns>
    public bool Equals(CSharpRewriter? other)
        => other is not null
        && RewritePublicToInternal == other.RewritePublicToInternal
        && AddAutoGeneratedAttribute == other.AddAutoGeneratedAttribute
        && AddAutoGeneratedHeader == other.AddAutoGeneratedHeader
        && AddEmbeddedAttribute == other.AddEmbeddedAttribute
        && AddGlobalUsings == other.AddGlobalUsings
        && AddNullableDirective == other.AddNullableDirective
        && RewriteTypeNames == other.RewriteTypeNames
        && AggressiveImportRemoval == other.AggressiveImportRemoval
        && RewriteExtensionCalls == other.RewriteExtensionCalls
        && (Configuration ?? RewriterConfiguration.Empty).Equals(other.Configuration ?? RewriterConfiguration.Empty);

    /// <inheritdoc/>
    public override bool Equals(object obj) => Equals(obj as CSharpRewriter);

    /// <inheritdoc/>
    public override int GetHashCode()
    {
        unchecked
        {
            int hashCode = RewritePublicToInternal.GetHashCode();
            hashCode = (hashCode * 397) ^ AddAutoGeneratedAttribute.GetHashCode();
            hashCode = (hashCode * 397) ^ AddAutoGeneratedHeader.GetHashCode();
            hashCode = (hashCode * 397) ^ AddEmbeddedAttribute.GetHashCode();
            hashCode = (hashCode * 397) ^ AddGlobalUsings.GetHashCode();
            hashCode = (hashCode * 397) ^ AddNullableDirective.GetHashCode();
            hashCode = (hashCode * 397) ^ RewriteTypeNames.GetHashCode();
            hashCode = (hashCode * 397) ^ AggressiveImportRemoval.GetHashCode();
            hashCode = (hashCode * 397) ^ RewriteExtensionCalls.GetHashCode();
            hashCode = (hashCode * 397) ^ (Configuration ?? RewriterConfiguration.Empty).GetHashCode();
            return hashCode;
        }
    }

    /// <summary>
    /// Adds required global using directives to the compilation unit.
    /// Runs after the main rewrite to ensure that only used global usings are added.
    /// </summary>
    private static CompilationUnitSyntax AddRequiredGlobalUsings(
        CompilationUnitSyntax root,
        SemanticModel semanticModel,
        Compilation compilation,
        HashSet<string> extensionNamespaces,
        CancellationToken cancellationToken)
    {
        CompilationUnitSyntax sourceRoot = root;
        var existingUsings = new HashSet<string>(sourceRoot.Usings.Select(GetUsingKey), StringComparer.Ordinal);
        var candidateKeys = new HashSet<string>(StringComparer.Ordinal);
        foreach (SyntaxTree tree in compilation.SyntaxTrees)
        {
            cancellationToken.ThrowIfCancellationRequested();
            SemanticModel globalUsingSemanticModel = compilation.GetSemanticModel(tree);
            foreach (UsingDirectiveSyntax directive in tree.GetCompilationUnitRoot(cancellationToken).Usings)
            {
                if (!directive.GlobalKeyword.IsKind(SyntaxKind.GlobalKeyword))
                {
                    continue;
                }

                UsingDirectiveSyntax candidate = directive.WithGlobalKeyword(default).WithoutTrivia();
                string key = GetUsingKey(candidate);
                if (existingUsings.Contains(key) || !candidateKeys.Add(key)
                    || !IsGlobalUsingUsed(directive, sourceRoot, semanticModel, globalUsingSemanticModel, extensionNamespaces, cancellationToken))
                {
                    continue;
                }

                if (!directive.StaticKeyword.IsKind(SyntaxKind.StaticKeyword)
                    && directive.Alias is null
                    && directive.Name is not null
                    && globalUsingSemanticModel.GetSymbolInfo(directive.Name, cancellationToken).Symbol is INamespaceSymbol namespaceSymbol)
                {
                    candidate = candidate.WithAdditionalAnnotations(new SyntaxAnnotation(
                        ScopedRewriter.ResolvableImport,
                        namespaceSymbol.ToDisplayString()));
                }

                root = root.AddUsings(candidate);
            }
        }

        return root;
    }

    private static string GetUsingKey(UsingDirectiveSyntax directive)
        => directive.WithGlobalKeyword(default).WithoutTrivia().ToString();

    /// <summary>
    /// Determines whether a compilation global using contributes a name or extension method used by the rewritten source.
    /// </summary>
    /// <param name="directive">The compilation-level global using to check.</param>
    /// <param name="root">The rewritten source syntax.</param>
    /// <param name="semanticModel">The semantic model for the rewritten source.</param>
    /// <param name="globalUsingSemanticModel">The semantic model for the tree declaring the global using.</param>
    /// <param name="extensionNamespaces">Namespaces containing extension methods still used by the source.</param>
    /// <param name="cancellationToken">A token for cancelling the operation.</param>
    /// <returns><see langword="true"/> if the using is needed by the source; otherwise, <see langword="false"/>.</returns>
    private static bool IsGlobalUsingUsed(
        UsingDirectiveSyntax directive,
        CompilationUnitSyntax root,
        SemanticModel semanticModel,
        SemanticModel globalUsingSemanticModel,
        HashSet<string> extensionNamespaces,
        CancellationToken cancellationToken)
    {
        if (directive.Alias is not null)
        {
            string aliasName = directive.Alias.Name.Identifier.ValueText;
            return root.DescendantNodes().OfType<IdentifierNameSyntax>().Any(identifier =>
            {
                cancellationToken.ThrowIfCancellationRequested();
                return identifier.Identifier.ValueText == aliasName
                    && semanticModel.GetAliasInfo(identifier, cancellationToken) is IAliasSymbol alias
                    && alias.Name == aliasName;
            });
        }

        ISymbol? target = directive.Name is null
            ? null
            : globalUsingSemanticModel.GetSymbolInfo(directive.Name, cancellationToken).Symbol;
        if (target is null)
        {
            return false;
        }

        if (target is INamespaceSymbol extensionNamespace
            && extensionNamespaces.Contains(extensionNamespace.ToDisplayString()))
        {
            return true;
        }

        foreach (SimpleNameSyntax name in root.DescendantNodes().OfType<SimpleNameSyntax>())
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (name.Ancestors().Any(ancestor => ancestor is UsingDirectiveSyntax)
                || name.Ancestors().OfType<QualifiedNameSyntax>().Any(qualifiedName => qualifiedName.Right.Span.Contains(name.Span)))
            {
                continue;
            }

            SymbolInfo symbolInfo = semanticModel.GetSymbolInfo(name, cancellationToken);
            IEnumerable<ISymbol> symbols = symbolInfo.Symbol is null
                ? symbolInfo.CandidateSymbols
                : symbolInfo.CandidateSymbols.Prepend(symbolInfo.Symbol);
            foreach (ISymbol symbol in symbols)
            {
                if (directive.StaticKeyword.IsKind(SyntaxKind.StaticKeyword)
                    ? IsMemberOfImportedType(symbol, target)
                    : target is INamespaceSymbol importedNamespace
                        && SymbolEqualityComparer.Default.Equals(symbol.ContainingNamespace, importedNamespace))
                {
                    if (name.Parent is not MemberAccessExpressionSyntax memberAccess
                        || memberAccess.Name != name
                        || symbol is IMethodSymbol { ReducedFrom: not null })
                    {
                        return true;
                    }
                }
            }
        }

        return false;
    }

    private static bool IsMemberOfImportedType(ISymbol symbol, ISymbol importedType)
    {
        if (importedType is not INamedTypeSymbol importedNamedType)
        {
            return false;
        }

        for (INamedTypeSymbol? containingType = symbol.ContainingType; containingType is not null; containingType = containingType.ContainingType)
        {
            if (SymbolEqualityComparer.Default.Equals(containingType.OriginalDefinition, importedNamedType.OriginalDefinition))
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Collects namespaces for extension methods the rewritten source still depends on, including implicit extension-based constructs.
    /// </summary>
    /// <param name="root">The rewritten source syntax.</param>
    /// <param name="semanticModel">The semantic model for the rewritten source.</param>
    /// <param name="cancellationToken">A token for cancelling the operation.</param>
    /// <returns>The namespace display names required for extension-method lookup.</returns>
    private static HashSet<string> GetExtensionNamespaces(
        CompilationUnitSyntax root,
        SemanticModel semanticModel,
        CancellationToken cancellationToken)
    {
        var extensionNamespaces = new HashSet<string>(StringComparer.Ordinal);
        foreach (SyntaxNode node in root.DescendantNodes())
        {
            cancellationToken.ThrowIfCancellationRequested();
            switch (node)
            {
                // Explicit calls such as value.Method() and conditional calls such as value?.Method().
                case MemberAccessExpressionSyntax or MemberBindingExpressionSyntax:
                    SymbolInfo symbolInfo = semanticModel.GetSymbolInfo(node, cancellationToken);
                    if (symbolInfo.Symbol is IMethodSymbol { ReducedFrom: not null } method)
                    {
                        AddMethod(method);
                        break;
                    }

                    // Binding failed or is ambiguous; retain namespaces of candidate extension methods.
                    if (symbolInfo.Symbol is null)
                    {
                        AddSymbols(symbolInfo);
                    }

                    break;

                // Query clauses such as from, where, let and join can bind implicit LINQ calls, including Cast<T>().
                case QueryClauseSyntax clause:
                    QueryClauseInfo queryInfo = semanticModel.GetQueryClauseInfo(clause, cancellationToken);
                    AddSymbols(queryInfo.CastInfo);
                    AddSymbols(queryInfo.OperationInfo);
                    break;

                // Query select/group clauses and individual orderby keys bind Select, GroupBy and ordering methods.
                case SelectOrGroupClauseSyntax or OrderingSyntax:
                    AddSymbols(semanticModel.GetSymbolInfo(node, cancellationToken));
                    break;

                // foreach can use an extension GetEnumerator(); tuple variables can also use extension Deconstruct().
                case CommonForEachStatementSyntax loop:
                    AddMethod(semanticModel.GetForEachStatementInfo(loop).GetEnumeratorMethod);
                    if (loop is ForEachVariableStatementSyntax deconstructionLoop)
                    {
                        AddDeconstruction(semanticModel.GetDeconstructionInfo(deconstructionLoop));
                    }

                    break;

                // await can bind an extension GetAwaiter() without an explicit method call.
                case AwaitExpressionSyntax awaitExpression:
                    AddMethod(semanticModel.GetAwaitExpressionInfo(awaitExpression).GetAwaiterMethod);
                    break;

                // Deconstruction assignments and declarations, such as (x, y) = value or var (x, y) = value.
                case AssignmentExpressionSyntax assignment when assignment.IsKind(SyntaxKind.SimpleAssignmentExpression):
                    AddDeconstruction(semanticModel.GetDeconstructionInfo(assignment));
                    break;
            }
        }

        return extensionNamespaces;

        void AddMethod(IMethodSymbol? method)
        {
            if (method is null)
            {
                return;
            }

            IMethodSymbol definition = method.ReducedFrom ?? method;
            if (definition.IsExtensionMethod)
            {
                _ = extensionNamespaces.Add(definition.ContainingNamespace.ToDisplayString());
            }
        }

        void AddSymbols(SymbolInfo info)
        {
            AddMethod(info.Symbol as IMethodSymbol);
            foreach (ISymbol candidate in info.CandidateSymbols)
            {
                AddMethod(candidate as IMethodSymbol);
            }
        }

        void AddDeconstruction(DeconstructionInfo info)
        {
            cancellationToken.ThrowIfCancellationRequested();
            AddMethod(info.Method);
            foreach (DeconstructionInfo nested in info.Nested)
            {
                AddDeconstruction(nested);
            }
        }
    }

    /// <summary>
    /// Removes resolvable namespace usings not needed for extension-method lookup, preserving aliases, static imports, and unresolved imports.
    /// </summary>
    /// <param name="root">The source syntax containing imports to clean up.</param>
    /// <param name="extensionNamespaces">Namespaces required by extension methods still used by the source.</param>
    /// <param name="cancellationToken">A token for cancelling the operation.</param>
    /// <returns>The source syntax with unused resolvable namespace usings removed.</returns>
    private static CompilationUnitSyntax RemoveUnusedNamespaceUsings(
        CompilationUnitSyntax root,
        HashSet<string> extensionNamespaces,
        CancellationToken cancellationToken)
    {
        var unusedImports = new List<UsingDirectiveSyntax>();
        foreach (UsingDirectiveSyntax node in root.DescendantNodes().OfType<UsingDirectiveSyntax>())
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (node.GlobalKeyword.IsKind(SyntaxKind.GlobalKeyword)
                || node.StaticKeyword.IsKind(SyntaxKind.StaticKeyword)
                || node.Alias is not null)
            {
                continue;
            }

            string? namespaceName = node.GetAnnotations(ScopedRewriter.ResolvableImport).SingleOrDefault()?.Data;
            if (namespaceName is not null && !extensionNamespaces.Contains(namespaceName))
            {
                unusedImports.Add(node);
            }
        }

        return root.RemoveNodes(unusedImports, SyntaxRemoveOptions.KeepExteriorTrivia)!;
    }

    private static MemberDeclarationSyntax AddTypeAttributes(
        MemberDeclarationSyntax declaration,
        SyntaxList<AttributeListSyntax> attributeLists,
        AttributeSyntax? generatedCodeAttribute,
        bool addEmbeddedAttribute,
        string lineEnding)
    {
        SyntaxList<AttributeListSyntax> updatedAttributes = AddAttributes(attributeLists, generatedCodeAttribute, addEmbeddedAttribute, lineEnding);
        if (updatedAttributes.Count == attributeLists.Count)
        {
            return declaration;
        }

        SyntaxToken typeToken = declaration.ChildTokens().First();
        SyntaxTriviaList leadingTrivia = attributeLists.Count == 0
            ? typeToken.LeadingTrivia
            : attributeLists.Last().GetLeadingTrivia();

        SyntaxTriviaList indentation = leadingTrivia.Count > 0 && leadingTrivia.Last().IsKind(SyntaxKind.WhitespaceTrivia)
            ? SyntaxFactory.TriviaList(leadingTrivia.Last())
            : default;

        if (attributeLists.Count == 0)
        {
            declaration = declaration.ReplaceToken(typeToken, typeToken.WithLeadingTrivia(indentation));
        }

        for (int index = attributeLists.Count; index < updatedAttributes.Count; index++)
        {
            updatedAttributes = updatedAttributes.Replace(updatedAttributes[index], updatedAttributes[index]
                .WithLeadingTrivia(attributeLists.Count == 0 && index == 0 ? leadingTrivia : indentation));
        }

        return declaration switch
        {
            BaseTypeDeclarationSyntax type => type.WithAttributeLists(updatedAttributes),
            DelegateDeclarationSyntax type => type.WithAttributeLists(updatedAttributes),
            _ => throw new ArgumentException("Expected a type declaration.", nameof(declaration)),
        };
    }

    private static SyntaxList<AttributeListSyntax> AddAttributes(
        SyntaxList<AttributeListSyntax> attributeLists,
        AttributeSyntax? generatedCodeAttribute,
        bool addEmbeddedAttribute,
        string lineEnding)
    {
        bool hasGeneratedCodeAttribute = generatedCodeAttribute is null || HasAttribute(attributeLists, "System.CodeDom.Compiler.GeneratedCodeAttribute");
        bool hasEmbeddedAttribute = !addEmbeddedAttribute || HasAttribute(attributeLists, "Microsoft.CodeAnalysis.EmbeddedAttribute");
        if (hasGeneratedCodeAttribute && hasEmbeddedAttribute)
        {
            return attributeLists;
        }

        var attributes = new List<AttributeSyntax>();
        if (!hasGeneratedCodeAttribute)
        {
            attributes.Add(generatedCodeAttribute!);
        }

        if (!hasEmbeddedAttribute)
        {
            attributes.Add(CreateAttribute("global::Microsoft.CodeAnalysis.Embedded"));
        }

        return attributeLists.AddRange(attributes.Select(attribute =>
            SyntaxFactory.AttributeList(SyntaxFactory.SingletonSeparatedList(attribute))
                .WithTrailingTrivia(SyntaxFactory.EndOfLine(lineEnding))));
    }

    private static AttributeSyntax CreateAttribute(string name, params string[] arguments)
        => SyntaxFactory.Attribute(
            SyntaxFactory.ParseName(name),
            arguments.Length == 0
                ? null
                : SyntaxFactory.AttributeArgumentList(SyntaxFactory.SeparatedList(arguments.Select(argument =>
                    SyntaxFactory.AttributeArgument(SyntaxFactory.LiteralExpression(
                        SyntaxKind.StringLiteralExpression,
                        SyntaxFactory.Literal(argument)))))));

    private static bool HasAttribute(SyntaxList<AttributeListSyntax> attributeLists, string attributeName)
        => attributeLists.SelectMany(list => list.Attributes).Any(attribute =>
        {
            string? resolvedName = attribute.GetAnnotations(Helper.ResolvedAttributeTypeAnnotation).SingleOrDefault()?.Data;
            if (resolvedName is not null)
            {
                return resolvedName.Equals(attributeName, StringComparison.Ordinal);
            }

            string name = attribute.Name.ToString();
            if (name.StartsWith("global::", StringComparison.Ordinal))
            {
                name = name["global::".Length..];
            }

            return name.Equals(attributeName, StringComparison.Ordinal)
                || (name + "Attribute").Equals(attributeName, StringComparison.Ordinal);
        });

    private static SyntaxTokenList MakeInternal(SyntaxTokenList modifiers)
    {
        foreach (SyntaxToken modifier in modifiers)
        {
            if (modifier.IsKind(SyntaxKind.PublicKeyword))
            {
                return modifiers.Replace(
                    modifier,
                    SyntaxFactory.Token(modifier.LeadingTrivia, SyntaxKind.InternalKeyword, modifier.TrailingTrivia));
            }
        }

        return modifiers;
    }
