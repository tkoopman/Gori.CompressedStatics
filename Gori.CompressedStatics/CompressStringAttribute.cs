using System;
using System.Diagnostics;

namespace Gori.CompressedStatics;

/// <summary>
/// Indicates that the string value of the property or method should be compressed at compile time using the specified compression algorithm and cache mode.
/// </summary>
/// <param name="value">The string value to be compressed.</param>
[Conditional("Gori_CompressedStatics_EmitAttributes")]
[AttributeUsage(AttributeTargets.Property | AttributeTargets.Method, AllowMultiple = false, Inherited = false)]
public sealed class CompressStringAttribute(string value) : Attribute
{
    /// <summary>
    /// Gets the string value to be compressed at compile time. If the
    /// property's type or method's return type is a byte array, the string
    /// value should be Base64 encoded and will be decoded at compile time
    /// before compressing.
    /// </summary>
    public string Value { get; } = value;

    /// <summary>
    /// Gets or sets the compression algorithm to use for compressing the string.
    /// Ignored if attribute is applied to a property that is covered by a <see cref="TarCompressAttribute"/>
    /// on the containing class.
    /// </summary>
    public CompressionAlgorithm Algorithm { get; set; }

    /// <summary>
    /// Gets or sets the cache mode to use for compressing the string.
    /// Setting this to non-default values will exclude this member from any <see cref="TarCompressAttribute"/>.
    /// </summary>
    public CompressionCacheMode CacheMode { get; set; }

    /// <summary>
    /// Gets or sets the transformer type name, optionally followed by <c>::MemberName</c>,
    /// used to transform the input string before compression.
    /// </summary>
    /// <remarks>
    /// Use <c>Namespace.Type, AssemblyName</c> to identify a type explicitly, or a full or short
    /// type name for fallback lookup. Unqualified names first try the built-in Gori.CompressedStatics
    /// namespace, with or without the Transformer suffix. Otherwise exact type names
    /// take precedence; only if no exact type is found is the optional <c>Transformer</c> suffix tried. For example,
    /// <c>CSharpRewriter</c> selects <c>CSharpRewriterTransformer</c>.
    /// Without a member name or explicit <see cref="TransformerArguments"/>, the type must
    /// be a concrete class with either a public static field or property named <c>Instance</c>
    /// of the exact same type, or have a public parameterless constructor. With a member name, the type must provide a
    /// public static field or property that supplies the transformer.
    /// The transformer must implement <c>IStringTransformer</c> for string results
    /// or <c>IBinaryTransformer</c> for byte array results.
    /// Transformer assemblies and their dependencies must be supplied as analyzer dependencies;
    /// transformers cannot be defined in the consuming project.
    /// While there is a <c>Base64</c> built-in transformer, it never needs to be specified explicitly; the generator
    /// automatically applies it when the property or method type is a byte array and no other transformer is specified.
    /// </remarks>
    /// <example>
    /// <c>CSharpRewriter</c>
    /// <c>Example.Transformers.MinifyJson, Example.Transformers</c> constructs a transformer.
    /// <c>Example.Transformers.Defaults, Example.Transformers::Json</c> obtains a transformer from a static member.
    /// </example>
    public string? Transformer { get; set; }

    /// <summary>
    /// Gets or sets explicit public constructor arguments for the selected input transformer.
    /// An empty array forces parameterless construction, bypassing the implicit static Instance member.
    /// </summary>
    /// <remarks>
    /// Omit this property to preserve singleton/parameterless fallback behavior. When specified,
    /// Transformer must name a type without a ::MemberName selector, and the array must not be null.
    /// Arguments use exact or assignable types only; numeric conversions, optional arguments, and
    /// params expansion are not performed. A unique most-specific public constructor is required.
    /// </remarks>
    /// <example>
    /// <c>[CompressFile("MyAttribute.cs", Transformer = "CSharpRewriter", TransformerArguments = [CSharpRewriterOptions.Default ^ CSharpRewriterOptions.AddAutoGeneratedAttribute])]</c>.
    /// </example>
    public object[]? TransformerArguments { get; set; }
}
